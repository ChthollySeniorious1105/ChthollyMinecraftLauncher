/// Rules text (GameDef.rules) for 四川麻将.
library;

const String sichuanRules = '''
# 牌与人数
- 4 人，108 张牌：只有万、筒、条三门（各 1~9 × 4 张），没有字牌和花牌。每人 13 张，庄家 14 张先打。
- 只能碰、明杠、暗杠、补杠，不能吃。
# 换三张与定缺
- 换三张（可在选项中关闭）：开局每人选 3 张同一花色的牌交出，方向随机（下家/对家/上家），所有人选好后同时交换。
- 定缺：之后每人选一门花色为“缺门”。手里有缺门牌时必须先打缺门牌；缺门牌不能碰杠；手里还有缺门牌时不能胡牌。
# 胡牌（血战到底）
- 胡牌型：4 组面子（刻子/顺子）+ 1 对将，或七对。没有起胡番数，平胡也可以胡。
- 血战到底：一家胡牌后离场（胡的牌亮出），其余玩家继续摸打，直到三家胡牌或牌墙摸完。一张牌可以被多家同时胡（一炮多响）。
- 番型：平胡 0、对对胡 1、清一色 2、带幺九 2、七对 2、清对 3、将对（全 258 碰碰胡）3、龙七对 3、清七对 4、清龙七对 5；每个“根”（4 张相同的牌，含杠）+1 番。
- 加番：杠上开花 +1、杠上炮 +1、抢杠胡 +1、海底捞月 +1。天胡、地胡直接按封顶计算。
- 得分 = 2^番（选项“封顶”：3/4/5/6 番，超过按封顶）。点炮者一人付；自摸时所有还没胡的玩家各付。
- 选项“自摸”：自摸加底（每家多付 1 分，默认）或自摸加番（+1 番）。
# 杠（刮风下雨）
- 明杠（直杠）：点杠者付 2 分；补杠（刮风）：未胡的每家各付 1 分；暗杠（下雨）：未胡的每家各付 2 分。杠分立即结算。
- 补杠时其他人可以抢杠胡。
# 流局结算（牌墙摸完）
- 查花猪：到最后手里还有缺门牌的玩家（花猪）赔给每位非花猪的未胡玩家封顶分。
- 查大叫：没听牌的玩家赔给每位听牌玩家其最大可能番数的分数。
- 退税：没听牌的玩家把本局收到的杠分退还给付杠分的人。
# 局数与名次
- 选项“局数”：4 / 8 / 16 局。下一局由本局第一个胡牌者坐庄（一炮多响时由点炮者坐庄），无人胡牌则庄家不变。
- 每局结束后所有人点“继续”进入下一局。全部局数打完后按总分排名，同分并列。
''';
