const String bangRules = '''
# 概述
西部无间道（BANG!）是 4~7 人的西部枪战身份游戏。每人抽一张身份牌：警长公开亮出，其余身份保密。
- 4 人：警长、叛徒、歹徒×2；5 人：再加副警长；6 人：再加歹徒；7 人：再加副警长。
- 警长和副警长：消灭所有歹徒和叛徒即获胜。
- 歹徒：杀死警长即获胜（无论歹徒自己是否还活着）。
- 叛徒：要成为最后一个活着的人。若警长死时只剩叛徒一人，叛徒获胜；否则歹徒获胜。

# 角色与生命
- 每人随机得到一名角色（16 个基础角色），生命上限为 4 或 3，警长额外 +1。开局手牌数 = 生命值。
- 生命值同时是手牌上限：回合结束时手牌多于生命值，必须弃到等于生命值。
- 角色能力在你的面板上可以看到，例如：小子威利可以无限出 BANG!，杀手斯莱伯的 BANG! 需要两张闪避，乔尔多内自带酒桶，保罗自带野马，罗丝自带瞄准镜等。

# 回合流程
- 1. 判定：面前有炸药先判定炸药（♠2~9 爆炸失去 3 点生命，否则传给下家），再判定监狱（♥ 越狱照常行动，否则跳过本回合；监狱都要弃掉）。
- 2. 摸 2 张牌（部分角色有特殊摸牌方式）。
- 3. 出牌：任意张数，但 BANG! 每回合只能打 1 张（火山连发或小子威利除外）；蓝色装备牌放在自己面前，同名装备只能有一张，武器只能有一把（新武器替换旧武器）。
- 4. 弃牌到手牌上限后结束回合，轮到左手边下一名存活玩家。

# 距离与射程
- 两人之间的距离 = 沿座位绕圈（只算活着的人）较近一侧的步数。野马让别人看你的距离 +1，瞄准镜让你看别人的距离 -1（最少为 1）。
- 不带武器射程为 1；火山连发 1、斯科菲尔德 2、雷明顿 3、卡宾枪 4、温彻斯特 5。BANG! 只能打射程以内的人；惊慌只能对距离 1 的人用。

# 牌
- BANG!：射击；闪避：抵消一次射击；啤酒：回复 1 点（只剩 2 人时无效）；酒馆：所有人回复 1 点；驿站摸 2；富国银行摸 3。
- 杂货铺：翻开存活人数张牌，从出牌者起依次每人挑一张。决斗：双方轮流弃 BANG!，先拿不出（或放弃）的人失去 1 点生命。
- 加特林：射击所有其他人；印第安人：所有其他人需弃一张 BANG!，否则失去 1 点生命。
- 惊慌：拿走距离 1 内一名玩家的一张牌；卡特巴卢：弃掉任意一名玩家的一张牌（可以指定装备，或随机抽一张手牌）。
- 酒桶：被射击时判定，♥ 视为闪避。监狱不能关警长。
- “拔枪！”判定：翻开牌堆顶一张，看花色点数决定结果。

# 死亡
- 生命降到 0 时，若手里有啤酒会自动喝下保命（只剩 2 人时啤酒无效）。仍为 0 则死亡，公开身份，手牌和装备弃掉。
- 杀死歹徒的人奖励摸 3 张牌；警长杀死副警长要弃掉所有手牌和装备。

# 本实现说明
- 反应（闪避、印第安人、决斗、杂货铺挑牌）按顺序逐个询问相关玩家。濒死时自动喝啤酒；席德·凯臣濒死时自动弃两张最不值钱的牌回血。
- 惊慌/卡特巴卢由出牌者选择对方的某件装备，或随机抽一张手牌。
- 电脑只根据公开的出牌记录（谁打了谁）和自己的身份判断敌友，不会偷看身份。
''';

