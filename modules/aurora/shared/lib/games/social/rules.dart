const String catanRules = '''
# 游戏概述
卡坦岛是一款资源经营与交易桌游，3~4 人。玩家在由 19 块地形组成的岛上建立村庄、城市和道路，率先达到胜利分者获胜。

# 地形与资源
- 森林产木材、山丘产砖块、草原产羊毛、田地产小麦、山脉产矿石，沙漠不产出。
- 每块地形有一个数字（2~12），掷骰结果等于该数字时，相邻的村庄得 1 张、城市得 2 张该资源。

# 开局
- 按顺序每人放 1 个村庄+1 条道路，再按逆序各放第 2 组；第 2 个村庄立即获得相邻地形各 1 张资源。
- 村庄之间至少隔 1 个路口（距离规则）。

# 回合流程
- 掷两颗骰子，所有人按点数收资源。
- 掷出 7：手牌超过 7 张的玩家弃掉一半（向下取整）；当前玩家移动强盗到另一块地形，并从该地形旁的一名玩家处随机抽 1 张牌。强盗所在地形不产出。
- 交易：可向所有玩家发出交易提议，也可与银行 4:1 交易，拥有港口时 3:1 或指定资源 2:1。
- 建造：道路（木+砖）、村庄（木+砖+羊+麦）、城市（2 麦+3 矿，升级村庄）、发展卡（羊+麦+矿）。

# 发展卡
- 骑士：移动强盗并抢牌；最先打出 3 张骑士且最多者获得“最大骑士团”+2 分。
- 道路建设：免费修 2 条路。丰收：从银行拿任意 2 张资源。垄断：指定一种资源，其他玩家必须全部交给你。
- 胜利分卡：1 分，结束前对他人保密。
- 每回合最多打出 1 张发展卡，当回合买的卡不能立即使用。

# 计分与胜负
- 村庄 1 分，城市 2 分，最长道路（至少 5 段连续且最长）+2 分，最大骑士团 +2 分，胜利分卡各 1 分。
- 在自己回合达到目标分（选项：8/10/12 分）立即获胜。获胜者第 1 名，其余按分数排名。
- 为防止对局无限进行，500 回合后按分数最高者判胜。

# 选项
- 地图：标准固定布局或随机布局。
- 电脑难度：简单的电脑选址随意、常常什么也不建就结束回合；困难的电脑总是选择最好的位置。
''';

const String avalonRules = '''
# 游戏概述
阿瓦隆是一款阵营推理游戏，5~10 人，分为正义方（亚瑟的忠臣）与邪恶方（莫德雷德的爪牙）。正义方要完成 3 次任务，邪恶方要让 3 次任务失败或者刺杀梅林。

# 角色
- 梅林（正义）：开局知道除莫德雷德外的所有邪恶方，但必须隐藏身份。
- 派西维尔（正义，可选）：知道梅林和莫甘娜是谁，但分不清二者。
- 忠臣（正义）：没有额外信息。
- 刺客（邪恶）：正义方完成 3 次任务后，可以刺杀一名玩家，刺中梅林则邪恶方翻盘。
- 莫甘娜（邪恶，可选）：在派西维尔眼中与梅林无法区分。
- 莫德雷德（邪恶，可选）：梅林看不到他。
- 奥伯伦（邪恶，可选）：不知道同伴，同伴也不知道他，但梅林能看到他。
- 爪牙（邪恶）：知道其他邪恶同伴（奥伯伦除外）。
- 邪恶方人数：5~6 人 2 名，7~9 人 3 名，10 人 4 名。

# 流程
- 组队：队长按本次任务人数（随人数与轮次变化）提名队员。
- 投票：所有人公开投赞成或反对，超过半数赞成则组队通过，否则队长顺延；连续 5 次被否决则邪恶方直接获胜。
- 任务：队员秘密出“成功”或“失败”牌，正义方只能出成功。出现 1 张失败（7 人以上第 4 次任务需 2 张）则任务失败。
- 共 5 次任务，先得 3 次成功或 3 次失败的一方结束任务阶段。

# 胜负
- 3 次任务失败或 5 次否决：邪恶方胜。
- 3 次任务成功：进入刺杀阶段，刺客刺中梅林则邪恶方胜，否则正义方胜。
- 获胜阵营全员第 1 名，失败阵营全员第 2 名。

# 选项与电脑
- 可选角色：派西维尔+莫甘娜、莫德雷德、奥伯伦。
- 电脑只根据自己身份能看到的信息和公开的任务记录做判断；简单的电脑常随意投票、随意刺杀，困难的电脑会更认真地分析谁可能是梅林。
''';

const String codenamesRules = '''
# 游戏概述
行动代号（Codenames）是一款团队猜词游戏，4~10 人，分为红蓝两队。桌上有 25 张词卡，每队各有一名队长（间谍首领），只有队长能看到钥匙卡：哪些词是红队特工、蓝队特工、路人，以及唯一的刺客。

# 分布
- 先手队 9 名特工，后手队 8 名，路人 7 名，刺客 1 名。

# 回合流程
- 队长给出提示：一个词+一个数字，例如“水果 2”，表示有 2 个己方特工和“水果”有关。
- 提示词必须是一个词，不能是场上未翻开的词，也不能包含场上的词或被其包含。
- 队员讨论后逐个翻卡，最多可以翻“数字+1”张，至少要翻 1 张；随时可以结束猜词。
- 翻到己方特工可以继续；翻到路人或对方特工，回合立即结束（对方特工算作对方找到）；翻到刺客，本队立即失败。

# 胜负
- 率先翻出本队全部特工的队伍获胜（对方帮你翻出的也算）。
- 翻到刺客的队伍直接落败。
- 获胜队全员第 1 名，失败队全员第 2 名。

# 选项
- 分组方式：按座位交替或随机分配；每队第一个成员担任队长。
- AI 电脑：开启后电脑队长由大模型根据钥匙卡构思提示词（严格检查：必须是单个词、不能与场上词重合或互相包含，否则改用普通电脑的提示）；电脑队员由大模型根据公开的提示记录挑选要翻的词。
- 电脑难度：简单的电脑队员经常乱翻，困难的电脑更准确。
''';

