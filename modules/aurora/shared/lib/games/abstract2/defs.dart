const _hiveRules = '''
# 概述
蜂巢（Hive）是没有棋盘的双人抽象棋：棋子本身组成“蜂巢”，在六角格上拼接。围住对方的蜂后即获胜。白方先行。

# 棋子（每方）
- 蜂后 ×1：沿蜂巢边缘滑动 1 格。
- 蜘蛛 ×2：沿蜂巢边缘恰好滑动 3 格，不能走回头路。
- 甲虫 ×2：移动 1 格，可以爬到其他棋子上方（形成叠放）；被压住的棋子不能移动，颜色按最上面的棋子算。
- 蚱蜢 ×3：沿直线跳过至少 1 枚连续的棋子，落在第一个空格。
- 蚂蚁 ×3：沿蜂巢边缘滑动任意格数。
- 扩展（选项开启时，每方各 1）：蚊子（模仿相邻棋子的移动方式；在蜂巢上方时只能按甲虫移动）、瓢虫（爬上蜂巢走 2 步，再下到空格，共 3 步）、鼠妇（移动 1 格；或把一枚相邻的、未被叠压的棋子搬过自己头顶放到自己旁边的空格）。

# 流程
- 每回合二选一：打入一枚新棋子，或移动一枚己方棋子（必须已经放下蜂后才能移动）。
- 打入：第一手随意；此后新棋子必须接触己方棋子、且不能接触任何对方棋子（按顶部颜色）。
- 第一手不能打入蜂后（锦标赛规则）；各自第 4 手结束前必须放下蜂后。
- 一体规则：任何时刻蜂巢都必须连成一片，移动过程中也不能把蜂巢断开。
- 自由移动规则：滑动的棋子必须能“挤”过去——两侧都被挡住的缝隙不能通过；滑动时必须始终贴着蜂巢。甲虫/瓢虫在高处移动时同样受到高度门限制。
- 鼠妇：不能搬动对方上一手刚移动/打入的棋子；被搬动的棋子下一回合不能移动或行动；搬运不能破坏一体规则或穿越门。
- 无棋可走时自动跳过。

# 胜负
- 某方蜂后六面全被棋子（任意颜色）包围，该方输。
- 一步棋同时围住双方蜂后为和棋。
- 同一局面出现第三次、或达到 400 手，判和。可认输、可求和、可悔棋。

# 操作
点选手中的棋子再点绿色格子打入；点选盘上己方棋子后点目标格移动。鼠妇搬运：点被搬的棋子，目标中会出现标有“搬”的格子。
''';

const _blokusRules = '''
# 概述
格格不入（Blokus）是 2~4 人的领地拼图游戏。每人 21 块颜色相同的多格骨牌（1 格 1 块、2 格 1 块、3 格 2 块、4 格 5 块、5 格 12 块，共 89 格）。
- 2 人：Blokus Duo 规则，14×14 棋盘，两个起始点（第 5 行第 5 列 与 第 10 行第 10 列）。
- 3~4 人：20×20 棋盘，每人从自己的角落开始（3 人时只用三个角）。

# 放置规则
- 按座位顺序轮流放置一块棋子，可任意旋转与翻转。
- 第一块必须覆盖自己的起始角（Duo：覆盖一个空着的起始点）。
- 之后每块必须至少与一块同色棋子“角对角”相接，并且绝不能与同色棋子“边对边”相邻。与其他颜色的棋子可以任意边相接。
- 棋子不能重叠，也不能超出棋盘。
- 无处可放的玩家停止放置，其余人继续；也可以主动放弃继续放置。所有人都停下时游戏结束。

# 计分（高级计分）
- 每剩一个未放下的小方格 −1 分。
- 21 块全部放完 +15 分；若最后放下的是 1 格小方块，再 +5 分。
- 分数最高者获胜，可并列。

# 其他
- 认输：两人局对手获胜；多人局认输者停止放置并记为最后一名，剩最后一人时直接结束。
- 两人局可以求和；可以悔棋（没有任何随机）。

# 操作
在下方棋子托盘选择一块，用“旋转/翻转”按钮（或右键旋转）调整方向，在棋盘上移动鼠标可看到半透明预览：绿色为合法，红色为不合法。
棋盘上的小圆点是你可以落角的位置。手机上先点一下预览，再点一次同一格确认放下。
''';

const _onitamaRules = '''
# 概述
师徒棋（Onitama）是 5×5 的双人对弈棋。每方 1 名师父（大棋子，站在中间的神殿格）与 4 名弟子。

# 招式卡
- 全套 16 张招式卡（虎、蟹、猴、鹤、龙、象、螳螂、野猪、蛙、鹅、马、鳗、兔、公鸡、牛、眼镜蛇），每局随机抽 5 张：双方各 2 张明牌，1 张放在一旁。
- 每张卡画着若干种相对位移。走棋时选自己的一张卡，把任意一枚己方棋子按卡上的一种位移移动（以自己的视角为准，“前”是朝向对方）。
- 不能移动到己方棋子所在格，也不能移出棋盘；移动到对方棋子所在格即吃掉它。
- 用过的卡交给对方：放到一旁，同时把原本在一旁的卡拿回自己手中。所以你用掉的卡，对手下一回合就可以拿去用。
- 旁边那张卡的印章颜色决定谁先手（红/蓝）。
- 若没有任何合法走法，必须选一张卡交换（不移动棋子）。

# 胜负
- 石之道：吃掉对方师父获胜。
- 水之道：己方师父走进对方的神殿格（对方底线中间）获胜。
- 同一局面出现三次或达到 300 手判和；可认输、求和、悔棋（随机只发生在开局抽卡）。

# 操作
先点选一张自己的卡（或直接点棋子），再点棋子，绿色格即可走的位置。卡片上的小棋盘中央黑格是棋子，彩色格是可去的位置。
''';

const _quartoRules = '''
# 概述
Quarto 是 4×4 棋盘上的双人棋。共 16 枚各不相同的棋子，每枚有四种二元属性：高/矮、深色/浅色、方/圆、空心/实心。棋子由双方共用。

# 流程
- 先手方先从剩余棋子中挑一枚“交给”对手。
- 对手把这枚棋子放在任意空格上，然后再从剩余棋子里挑一枚交给另一方……如此交替。
- 也就是说：你放的棋子永远是对手替你挑的，而你要替对手挑选他下一枚放的棋子。

# 胜负
- 放下棋子后，若某一行、某一列或某条对角线上的 4 枚棋子至少有一个共同属性（例如全是高的，或全是空心的），放下这枚棋子的人获胜（叫出 Quarto）。
- 方块变体（选项）：任意相邻 2×2 小方块的四枚棋子共享一个属性也算获胜。
- 16 枚全部放完仍无人获胜为和棋。
- 本实现自动判定胜利（无需喊出）。可认输、求和、悔棋。

# 棋子图示
高的棋子画得大、矮的小；深色为棕色、浅色为米色；方形/圆形如其形；空心的顶部有一个洞。

# 操作
挑选阶段：在棋子库中点一枚棋子交给对手。放置阶段：点棋盘上的空格放下对手给你的棋子。
''';

