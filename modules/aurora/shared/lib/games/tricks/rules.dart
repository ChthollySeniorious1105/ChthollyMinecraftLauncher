const spadesRules = '''
# 概要
- 四人，对家为搭档（南北 vs 东西）。一副 52 张，每人 13 张，A 最大。黑桃永远是将牌。

# 叫墩
- 从发牌人左手开始，每人依次叫自己预计能赢的墩数（0~13）。叫 0 叫“零墩（Nil）”，表示自己一墩都不赢。
- 选项“盲零”开启时：落后对方 100 分及以上的一队，其队员可以在看牌之前叫“盲零”，成功 +200，失败 -200。
- 全队的定约 = 两人叫墩之和（零墩玩家不计入）。

# 出牌
- 发牌人左手首出。必须跟出首出花色，没有可以用黑桃将吃或垫牌。
- 黑桃被“破”（有人垫过黑桃）之前不能首出黑桃，除非手里只剩黑桃。
- 首出花色最大的牌赢得该墩，若有黑桃则最大的黑桃赢；赢者领出下一墩。

# 计分
- 完成定约：得 10 × 定约墩数，每多赢一墩得 1 分并记 1 个“袋”（bag）。
- 未完成定约：扣 10 × 定约墩数。
- 零墩：该玩家一墩不赢 +100，否则 -100（零墩玩家赢的墩不算搭档的，但算作袋）；盲零为 ±200。
- 袋累计满 10 个时扣 100 分，袋数减 10。

# 胜负
- 选项“目标分”：500 分或 250 分。有队伍达到目标分、或有队伍总分跌到 -200 及以下时比赛结束：只有一队跌破时另一队获胜，否则总分高者获胜（双方同分则继续打）。
- 选项“局数上限”：不限 / 5 局 / 10 局，到达局数按总分决胜负，同分为平局。
- 名次：胜队两人都是第 1，败队两人都是第 2；平局全部第 1。

