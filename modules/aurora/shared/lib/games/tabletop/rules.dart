const loveLetterRules = '''
# 概述
- 2019 版《情书》，共 21 张牌。每局每人只持 1 张手牌，轮到自己时摸 1 张、打出 1 张并执行效果。
- 每局的胜者获得 1 枚好感标记；率先集齐目标数量者赢得整场游戏：2 人 6 枚、3 人 5 枚、4 人 4 枚、5~6 人 3 枚。

# 准备
- 洗牌后面朝下移除 1 张（本局不用，牌库摸完时王子效果可摸到它）。
- 2 人游戏额外翻开 3 张面朝上移除，所有人可见。
- 每人摸 1 张。第一局随机先手，之后由上一局的胜者先手。

# 卡牌（点数 / 张数 / 效果）
- 0 间谍 ×2：本局结束时，若你是唯一打出或弃置过间谍的存活玩家，额外获得 1 枚标记。
- 1 卫兵 ×6：指定一名其他玩家并猜一张非卫兵的牌，猜中则其出局。
- 2 牧师 ×2：秘密查看一名其他玩家的手牌。
- 3 男爵 ×2：与一名其他玩家秘密比较手牌，点数小者出局，相同则无事。
- 4 侍女 ×2：直到你的下个回合，你不能被任何卡牌选为目标。
- 5 王子 ×2：令一名玩家（可以是自己）弃掉手牌并重摸一张；弃掉公主者出局。
- 6 大臣 ×2：从牌库摸 2 张，三张中保留 1 张，其余按你选择的顺序放回牌库底。
- 7 国王 ×1：与一名其他玩家交换手牌。
- 8 伯爵夫人 ×1：若你另一张手牌是国王或王子，必须打出伯爵夫人。
- 9 公主 ×1：打出或被迫弃掉公主时你立即出局。
- 若所有其他玩家都受侍女保护，需要目标的牌照常打出但没有效果（王子则只能指定自己）。

# 一局的结束
- 只剩 1 名存活玩家时，其获胜。
- 牌库摸完（打完当前回合）时，存活玩家亮出手牌，点数最大者获胜；平局比较弃牌点数总和，仍平则共同获胜。
- 间谍奖励单独结算，可与胜者是同一人。

# 胜负与名次
- 有人达到目标标记数立即结束整场游戏。名次按标记数排列（达到目标者并列第 1）。

# 认输
- 认输的玩家本局立即出局，并且之后各局都不再参与，名次排在所有未认输玩家之后（越早认输名次越靠后）。
- 只剩 1 名未认输的玩家时，该玩家直接获胜。
''';

const yahtzeeRules = '''
# 概述
- 每人一张记分表，共 13 个计分项。游戏共 13 轮，每轮每人一个回合，每回合必须把结果填入一个尚未使用的计分项（可以填 0 分）。
- 13 项全部填满后总分最高者获胜，平分并列。支持 1 人单机挑战高分。

# 回合流程
- 每回合最多掷 3 次骰子：第一次掷全部 5 颗，之后可以任意保留部分骰子，重掷其余骰子。
- 可以在任意一次掷骰后提前选择计分项结束回合。

# 上半区
- 一点 ~ 六点：对应点数的骰子点数之和。
- 上半区合计达到 63 分（相当于每种点数各 3 颗），额外奖励 35 分。

# 下半区
- 三条：至少 3 颗相同，得 5 颗骰子点数总和。
- 四条：至少 4 颗相同，得 5 颗骰子点数总和。
- 葫芦：3 颗相同 + 另 2 颗相同，25 分（5 颗全相同不算葫芦，除非触发快艇百搭规则）。
- 小顺：含 4 个连续点数，30 分。
- 大顺：5 个连续点数，40 分。
- 快艇：5 颗全相同，50 分。
- 全计：任意组合，点数总和。

# 快艇奖励与百搭
- 如果快艇项已填 50 分后再次掷出快艇，每次额外奖励 100 分。
- 已填过快艇项（50 或 0）后再掷出快艇时适用百搭规则：若对应点数的上半区项还空着，必须填入该项；否则可填任意空着的下半区项，葫芦 / 小顺 / 大顺按满分计；下半区也填满时只能在上半区空项填 0。

# 认输
- 认输的玩家不再进行回合，名次排在所有未认输玩家之后（越早认输越靠后）。
- 多人游戏中只剩 1 名未认输玩家时游戏立即结束，该玩家获胜；单人游戏认输即结束。
''';

const splendorRules = '''
# 概述
- 扮演文艺复兴时期的宝石商人：收集宝石筹码、购买发展卡、吸引贵族来访。发展卡提供永久宝石折扣和声望分。
- 有玩家在自己回合结束时达到 15 分后，打完当前这一轮（直到先手玩家的上家）游戏结束。

# 准备
- 5 种宝石（白蓝绿红黑）各 4/5/7 枚（2/3/4 人），黄金 5 枚。
- 1~3 级发展卡各翻开 4 张；翻开“人数 + 1”位贵族。随机选择先手。

# 回合行动（四选一）
- 拿 3 枚不同颜色的宝石（场上可拿的颜色不足 3 种时，拿全部可拿的颜色）。
- 拿 2 枚同色宝石：该颜色在拿取前至少剩 4 枚。
- 保留 1 张牌：桌面上的明牌或任一级牌堆顶的暗牌放入手中（最多保留 3 张），并获得 1 枚黄金（如有）。暗保留的牌其他玩家看不到内容。
- 购买 1 张发展卡：桌面上的或自己保留的。已有发展卡的颜色提供永久折扣，不足部分可用黄金当任意颜色支付。买走后立即补牌。
- 如果确实没有任何可执行的行动，只能跳过；所有人连续多次无法行动时游戏结束。

# 宝石上限
- 回合结束时手中宝石（含黄金）不得超过 10 枚，超过需要退回多余的宝石。

# 贵族
- 回合结束时，若你的发展卡折扣满足某位贵族的要求，其自动来访并提供 3 分；同时满足多位时选择 1 位（每回合最多 1 位）。

# 胜负与名次
- 终局时声望分最高者获胜；同分时购买发展卡数量较少者名次靠前；仍相同则并列。
- 名次按上述比较依次排列。

# 认输
- 认输的玩家退还所有宝石筹码，之后跳过其回合，名次排在所有未认输玩家之后（越早认输越靠后）。
- 只剩 1 名未认输的玩家时，游戏立即结束，该玩家获胜。
''';

const liarsBarRules = '''
# 概述
- 围坐酒馆的骗子们轮流虚张声势，被识破的人要对自己的左轮开一枪。每把左轮 6 个弹膛只有 1 发子弹（位置随机、每人独立），开枪次数越多越危险。
- 最后的幸存者获胜。

# 骗子牌桌（默认）
- 牌组：Q、K、A 各 6 张 + 2 张王牌（5 人以上两副牌）。每轮每位存活玩家发 5 张，并随机指定本轮“桌牌”（Q/K/A 之一）。
- 轮到你时面朝下打出 1~3 张牌，声称它们都是桌牌；王牌可当任意桌牌。
- 下家可以选择继续出牌，或者喊“骗子”翻开上家刚打出的牌：有一张不是桌牌（或王牌），出牌者开枪；否则喊骗子的人开枪。
- 手牌打完的玩家不再出牌；若轮到的玩家已无手牌，只能喊骗子。开枪后重新发牌开始新一轮，由开枪者（若已倒下则为其下家）先出。

# 恶魔牌
- 同牌桌规则，但牌组中有 1 张恶魔牌（视为真话牌）。若恶魔牌被喊骗子翻开且其余都是真话，则除出牌者外所有存活玩家都要开枪。

# 混沌模式
- 牌组中有 2 张混沌牌（视为真话牌）。被翻开的牌中含混沌牌时，出牌者和喊骗子的人都要开枪。

# 骗子骰子
- 每人 5 颗骰子，秘密摇骰后轮流叫价“场上至少有 N 个 X 点”，后叫者必须叫更多的个数，或同个数更大的点数。
- 任何人可以对上家的叫价喊骗子，开骰计数：叫价成立则喊骗子者开枪，否则叫价者开枪。

# 经典吹牛骰
- 叫价规则同骗子骰子，但没有左轮：输的一方失去 1 颗骰子，失去全部骰子者出局。

# 选项
- 玩法：选择以上五种模式之一。
- 骰子 1 点万能（仅骰子模式有效）：开启时 1 点可算作任意点数（叫 1 点时只算 1 点本身），且 1 点在同数量叫价中视为最大点数。

# 胜负与名次
- 最后一名存活者第 1 名，其余按出局先后排名（越晚出局越靠前，同时出局并列）。若所有人同时倒下，他们并列第 1。

# 认输
- 认输视为立即出局（排在当前所有存活者之后）。若剩余存活者不少于 2 人，本轮作废并重新发牌/摇骰继续；只剩 1 人时其获胜。
''';
