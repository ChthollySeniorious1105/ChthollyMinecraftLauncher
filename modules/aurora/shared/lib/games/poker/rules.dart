const caboRules = '''# 概述
- 2~4 人，牌面数值 0~13（0 和 13 各 2 张，1~12 各 4 张）。每人面前扣着 4 张牌，目标是让自己面前的牌总点数尽量小。
- 多局累计：每局按点数加分，有人总分超过“目标分”（50 或 100）时游戏结束，总分最低者获胜（分数相同名次并列）。

# 开局
- 每人偷看自己面前的任意 2 张牌，之后只能靠记忆。翻开弃牌堆第一张。

# 回合
- 轮到你时三选一：从牌堆摸一张、拿弃牌堆顶的牌、或者喊“CABO”。
- 摸到的牌可以和自己面前的一张牌交换（换下的牌弃掉），也可以直接弃掉。
- 多张交换：可以用一张牌同时替换自己多张点数相同的牌（换下的全部弃掉，面前的牌变少）；如果选中的牌点数不一致，则全部公开、保留，并把摸到的牌作为罚牌加到面前。
