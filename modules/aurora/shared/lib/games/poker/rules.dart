- 牌堆用完时，除顶牌外的弃牌堆重新洗入牌堆。

# 本实现说明
- 两人对局时可以认输，认输方直接判负。
- 与原版的差异：没有“踢人”（Kamikaze，两张 12 两张 13）特殊计分。
