const String halligalliRules = '''
# 游戏概述
德国心脏病（Halli Galli）是一款考验眼力与反应速度的派对游戏，2~6 人。56 张水果牌平均发给所有玩家，每人面前一叠背面朝上的牌。

# 牌组
- 共 4 种水果：香蕉、草莓、青柠、李子，每种 14 张。
- 每张牌上有 1~5 个同种水果（每种水果：1 个×5 张、2 个×3 张、3 个×3 张、4 个×2 张、5 个×1 张）。

# 流程
- 从 1 号位开始，按顺序轮流把自己牌堆顶的一张牌翻开，放在自己面前的翻开牌堆上（盖住之前翻开的牌）。
- 桌面上只看每个人翻开牌堆最上面的那一张。
- 任何时候，只要桌面上某一种水果的总数恰好为 5 个，所有玩家都可以抢着拍铃。

# 拍铃
- 拍对（某种水果恰好 5 个）：最先拍铃的玩家收走桌上所有翻开的牌，放到自己牌堆底部，并由他接着翻牌。
- 拍错（没有任何水果恰好 5 个）：拍错的玩家要给其他每位仍有牌的玩家各罚 1 张牌。
- 拍铃以网络先到为准，晚到的会提示“慢了一步”。

# 出局与胜负
- 手上（牌堆+翻开牌）没有牌的玩家出局，轮到他时自动跳过。
- 只剩一名玩家有牌、所有人都翻完且无法再拍铃、或达到翻牌上限时游戏结束。
- 按剩余牌数排名，牌最多者获胜；牌数相同名次并列。

# 选项
- 电脑反应：电脑玩家看到 5 个水果后拍铃的反应速度（慢/普通/快）。
- 翻牌上限：300 次或 600 次，防止对局无限进行。
- 电脑难度：简单的电脑反应更慢，偶尔还会拍错铃；困难的电脑反应更快。
