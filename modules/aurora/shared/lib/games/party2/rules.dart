const String bullscowsRules = '''
# 游戏概述
猜数字（1A2B，又称 Bulls and Cows）是经典的逻辑推理游戏，2~6 人。每位玩家设定一个秘密密码，轮流去猜下家的密码，根据反馈逐步缩小范围。

# 设定密码
- 开局每人设定一个 3/4/5 位（由选项决定）的数字密码，各位数字互不相同，可以以 0 开头。
- 所有人设定完毕后开始猜测，从 1 号位开始轮流进行。

# 反馈规则
- 每次猜测都会得到形如 xAyB 的反馈：
- A：数字正确且位置也正确的个数。
- B：数字正确但位置不对的个数。
- 例如密码 1234，猜 1325 → 1A2B（1 位置对，3、2 数字对位置不对）。
- 所有猜测与反馈都是公开的，其他玩家也可以借此推理。

# 模式
- 抢先破解：每人的目标固定为下家，第一个完全猜中（全部为 A）的玩家立即获胜。
- 淘汰接力：猜中目标后目标出局，猜中者接手出局者原来的目标，继续猜；最后存活的玩家获胜。

# 结束与名次
- 有人获胜时游戏结束，获胜者第 1 名，其余并列第 2 名。
- 达到 40 轮上限仍无人破解时，按每人对当前目标“最接近”的一次猜测（A 优先、其次 B）判定胜者。

# 电脑难度
- 简单：随便挑一个大致符合反馈的数，偶尔会忘记一条线索。
- 普通：在所有符合反馈的候选中抽样，选择最能缩小范围的猜测。
- 困难：更大范围地评估候选，通常 5~7 次内破解 4 位密码。
''';

const String turtlesoupRules = '''
# 游戏概述
海龟汤是一款情境推理游戏，3~12 人。主持人（GM，默认为房主）掌握一个离奇故事的完整真相（汤底），其他玩家只知道故事的表面描述（汤面），通过提问来还原真相。

# 流程
- 准备：GM 查看题目，可以换题（最多 10 次）；选择“GM自拟”时由 GM 自己输入标题、汤面和汤底。GM 点击开始后公布汤面。
- 提问：玩家随时可以提出只能用“是/否”回答的问题，每人同一时间只能有一条等待回答的问题或猜测。
- GM 用以下五种之一回答问题：是、否、无关、是也不是、很接近。
- 猜汤底：玩家认为已经知道真相时，可以提交一段完整猜测，每题每人最多 3 次。GM 判定：猜对了 / 很接近 / 不对。
- 有人猜对、GM 主动公布、或提问与猜测次数都用完时，公布汤底，进入下一题。

# 计分
- 提出的问题被回答“是”或“很接近”：+1 分（鼓励问出好问题）。
- 猜中汤底：+5 分。
- 全部题目结束后按总分排名，同分并列；GM 不参与计分，记为第 1 名。

# 选项
- 来源：内置原创题库；服务器自定义题库（words/turtlesoup.txt，格式“标题|汤面|汤底”，没有时自动改用内置）；GM 自拟。
- 题数：本局连续进行 1~3 题。
- 每题提问上限：所有玩家合计可提问的次数，用完后只能猜汤底。
- AI 电脑：开启后，电脑主持人由大模型根据汤底认真回答每个问题并判定猜测；电脑玩家由大模型根据问答记录提出有针对性的问题并尝试还原真相（它看不到汤底）。服务器未配置大模型或调用失败时自动退回普通电脑。

# 小贴士
- 先问大方向（是否有人死亡、是否故意、是否有其他人参与），再抓住“是”和“很接近”深挖。
- 汤面中不合常理的细节往往就是突破口。
''';

const String decryptoRules = '''
# 游戏概述
截码战（Decrypto）是一款团队密码推理游戏，4~8 人，分为红队（偶数座位）与蓝队（奇数座位）。每队有 4 个编号 1~4 的秘密关键词，只有本队成员能看到。

# 每轮流程
- 每队轮流由一名队员担任加密者，加密者拿到一个 3 位密码（1~4 中 3 个不同数字，例如 3-1-4）。
- 给线索：加密者按密码顺序给出 3 条线索，每条对应一个关键词（例如 3 号词是“大海”，可以给“蓝色”）。线索每条最多 12 字，不能直接说出关键词。
- 猜码：本队其他成员根据线索猜本队密码；从第 2 轮起，双方还要尝试拦截对方的密码（只能依据对方历史上公开的线索推断）。
- 公布结果：显示正确密码与双方的猜测，所有线索按编号记入公开历史。

# 胜负
- 队友没猜对本队密码：失误 +1。
- 成功拦截对方密码：拦截 +1。
- 某队拦截达到 2 次即获胜；某队失误达到 2 次即落败。
- 双方同时触发或进行满 8 轮时，按“拦截 − 失误”比较；仍然相同则进入决胜：各队猜对方的 4 个关键词，猜中多者获胜，再相同则平局。
- 获胜队全员第 1 名，失败队全员第 2 名；平局全员第 1 名。

# 选项
- 词库：内置词库、服务器自定义词库（words/decrypto.txt）或两者混合。
- AI 电脑：开启后，电脑加密者由大模型根据本队关键词构思线索；电脑队员与拦截者由大模型根据线索历史推理密码。拦截时大模型看不到对方关键词。失败时自动退回普通电脑。
- 电脑难度：简单的电脑更常乱猜，困难的电脑拦截时总是根据历史推理。

# 技巧
- 线索既要让队友一眼看懂，又要避免和以往线索太相似，否则对手会从历史中推出对应关系。
''';
