/// 规则说明（GameDef.rules）。
const String drawguessRules = '''
# 游戏概述
你画我猜是经典的派对绘画游戏，3~12 人。每轮一名玩家当画手，根据词语作画，其他玩家在聊天框里猜词，猜得越快得分越高。

# 流程
- 轮流担任画手，每人画 1~3 次（选项）。
- 选词：画手从 3 个候选词中选 1 个（15 秒内不选自动选第一个），或由系统随机给词；GM 出题模式下由出题人为每位画手出题（可附类别提示）。
- 作画：画手在画布上作画，可以换颜色、粗细、撤销和清空；画面上不能写出答案文字。
- 猜词：其他玩家直接输入答案，猜对后不能再猜；答案与词语完全一致（忽略空格和大小写）才算对。含有答案中某个字的猜测会显示为“接近了”，内容只有自己和画手可见。

# 提示（可关闭）
- 作画开始即显示字数。
- 过了 1/3 时间显示类别。
- 过了 2/3 时间揭示其中一个字。

# 计分
- 猜对的玩家按先后得分：第 1 个 10 分，第 2 个 8 分，然后 6、5、4、3 分，之后每人 2 分。
- 画手每有 1 人猜对得 2 分。
- 所有人猜对或时间到时本轮结束，公布答案。全部轮次结束后按总分排名，同分并列；出题人不参与排名。

# 选项
- 出题方式：系统词库或 GM 出题（至少 4 人，房主当出题人，可提前结束本轮）。
- 每轮时间 60/80/120 秒；选词 3 选 1 或随机；提示开关；词库：内置、服务器自定义（words/drawguess.txt，每行“词语|类别”）或混合。
- AI 电脑：开启后电脑猜词者由大模型“看图”猜词（需服务器支持图片），会参考字数、类别和已揭示的字，每轮最多看图 3 次；电脑画手由大模型构思简笔画并一笔一笔画出来。失败时自动退回普通电脑。
- 电脑难度：简单的电脑经常不看提示乱猜。
''';

const String telephoneRules = '''
# 游戏概述
传话画画（Gartic Phone）是一款“画画版传话游戏”，3~12 人。每人拥有一本“本子”，本子在玩家之间传递，文字和画交替出现，最后逐本揭晓，看看意思跑偏了多远。

# 流程
- 第 1 轮 写题：每人在自己的本子里写一句话（最多 40 字），不写则系统随机给一个词。
- 之后每轮本子传给下一位：拿到文字的人要把它画出来，拿到画的人要用一句话描述画的内容，作画与描述交替进行。
- 每人每轮只能看到手中本子的上一页，看不到更早的内容。
- 共进行与人数相同的轮数，保证每个人都经手每本本子一次，而且不会拿回自己的本子。
- 时间到时，没提交的内容按当前草稿自动提交（作画则提交已画的部分）。

# 揭晓
- 所有本子完成后，由房主逐页翻开每一本，大家一起看从第一句话到最后一页的变化。
- 揭晓过的页面可以点赞（不能给自己点赞），结束时展示获赞最多的作品。
- 本游戏不计分，所有人名次相同。

# 选项
- 作画时间：60/90/120 秒；写字时间：30/45/60 秒。
- AI 电脑：开启后电脑玩家由大模型写开场句子、看图描述上一位的画（需服务器支持图片）、并根据文字构思简笔画一笔一笔画出来；失败时自动退回普通电脑。
''';
