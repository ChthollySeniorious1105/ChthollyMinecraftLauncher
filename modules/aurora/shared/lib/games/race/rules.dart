const quoridorRules = '''
# 概述
- 2~4 人，9×9 棋盘。每人一个棋子从自己那条边的中点出发，率先到达对面一整条边的任意格子者胜。
- 每人拥有若干块墙：2 人各 10 块，3 人各 7 块，4 人各 5 块。每块墙长两格，放在格线上。
# 回合
- 每回合二选一：
- 移动：把棋子向上下左右移动一格，不能穿墙。
- 放墙：在格线交点处放一块横墙或竖墙，挡住两格长的通道。墙不能重叠、不能十字交叉，并且不能把任何棋子完全封死（必须始终留有通往终点的路）。
- 跳子：若相邻格有其他棋子，可以直接跳过它；若它身后被墙或棋盘边挡住，可以斜跳到它的左右两侧。
