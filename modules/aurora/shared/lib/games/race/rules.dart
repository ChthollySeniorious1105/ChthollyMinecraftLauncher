const ludoRules = '''
# 概述
- 2~4 人，每人四架同色飞机，从机库起飞，沿外圈顺时针飞行一周后进入本色终点跑道，四架全部到达终点者胜。2 人时使用对角的两种颜色。
# 回合流程
- 轮到自己时掷骰子。掷出起飞点数（见选项）可让一架机库里的飞机起飞到起飞格，否则只能移动已在场上的飞机。
- 掷出 6 可以再掷一次。若开启“连掷三个6 本轮作废”，同一回合第三次掷出 6 时本轮作废，直接轮到下家。
- 没有可移动的飞机时自动跳过；只有一种走法时自动移动。
# 特殊格
- 跳格：停在与自己同色的格子上，会再向前跳到下一个同色格（+4 格）。
- 飞越：停在本色的飞越格时，沿虚线直接飞到对面的同色格（捷径）。跳格后恰好落在飞越格也会继续飞越。
- 撞子：停下（包括跳格、飞越的每一个落点）时若有对手的飞机，把它们全部撞回机库。
- 进入本色终点跑道后对手无法撞你。
# 到达终点
- 选项“需要精确点数”：点数超过终点时多出的步数要倒退回来；“点数超出也算到达”：只要够就算到达。
# 胜负与名次
- 第一个让四架飞机全部到达终点者获胜；其余玩家按飞机总前进距离排名。
- 认输：认输的玩家飞机全部移除，之后跳过其回合，名次排在最后；只剩一人时该玩家获胜。
# 电脑难度
- 简单：经常随便挑一架飞机走；普通：优先撞子、起飞、躲避危险；困难：更重视安全与收尾。
''';

