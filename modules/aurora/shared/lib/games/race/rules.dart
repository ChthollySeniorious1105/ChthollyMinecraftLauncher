# 认输、和棋、悔棋
- 认输：两人时对手直接获胜；多人时该玩家出局（棋子留在原地作为障碍，但不再要求为其留路），排在最后，只剩一人时其获胜。
- 所有真人同意求和时以和棋结束，所有人并列第一。
- 支持悔棋（完全确定、无隐藏信息）。
# 电脑难度
- 简单：经常乱走、很少放墙；普通：落后时用墙阻挡领先者；困难：更积极地放墙，并兼顾阻挡所有对手。
