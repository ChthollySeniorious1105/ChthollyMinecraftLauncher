const battleshipRules = '''
# 概述
- 两人对战。双方各自在 10×10 的格子中秘密布置若干架飞机（选项：3 架或 2 架），然后轮流轰炸对方的格子，先炸毁对方全部飞机的机头者胜。
# 飞机形状
- 每架飞机占 10 格：机头 1 格、机翼 5 格（横排）、机身 1 格、机尾 3 格，呈“士”字形的飞机状，可朝上下左右四个方向摆放。
- 飞机不能超出边界，也不能互相重叠。
# 布置阶段
- 双方同时布置，可以旋转、拖动，也可以随机布局。双方都确认后随机决定谁先轰炸。
# 轰炸阶段
- 每回合轰炸对方一个没炸过的格子，结果公开：
- 空：没有打中飞机。
- 伤：打中飞机的机翼、机身或机尾。
- 毁：打中机头，这架飞机被击落。
- 无论结果如何都轮到对方（本实现不设“命中再炸一次”）。
# 胜负
- 先击落对方全部飞机（炸中全部机头）的一方获胜。游戏结束后双方的布局都会公开。
- 任何时候都可以认输，对手直接获胜。
# 电脑难度
- 简单：一半概率随机轰炸；普通：根据已知“空/伤/毁”计算每个格子是机头的概率；困难：同样的概率推算，但更重视用机身信息缩小范围。
''';

const davinciRules = '''
# 概述
- 2~4 人。牌共 24 张：黑、白两色各有 0~11。可选加入黑白两张百搭牌“-”。
- 开局每人摸 4 张（4 人时 3 张），按数字从小到大从左往右排列，同数字时黑色在左。自己能看到自己的牌，对手只能看到颜色。
# 回合
- 轮到你时先从牌堆摸一张新牌（牌堆空了就不摸），按顺序插入自己的牌列。摸到百搭牌时可以任意选择插入位置。
- 然后必须猜一次：指定一名对手的一张暗牌，说出它的数字。
- 猜对：该牌翻开。你可以继续猜，也可以停止（新摸的牌保持暗置）。
- 猜错：必须翻开自己刚摸的那张牌；如果本回合没有摸牌，则自选一张自己的暗牌翻开。回合结束。
- 猜错的数字会被标记在那张牌上，所有人都能看到。
# 推理技巧
- 牌列一定按大小排列，已翻开的牌会限制两侧暗牌的范围；自己手里和已翻开的牌不可能在别处出现。
# 胜负与名次
- 一名玩家的牌全部被翻开即出局。最后保留暗牌的玩家获胜；越晚出局名次越好。
- 认输：该玩家所有牌翻开，视为出局，排名按出局顺序；两人时对手直接获胜。
# 电脑难度
- 简单：经常乱猜、见好不收；普通：挑可能性最少的牌来猜；困难：只在确定时连续猜，不冒险。
''';
