const String hkmjRules = '''
# 牌与流程
- 4 人，144 张牌：万筒条 1~9、东南西北中发白各 4 张，另有春夏秋冬梅兰竹菊 8 张花牌。每人 13 张，庄家先摸。
- 摸到花牌立即亮出并补牌；集齐 8 张花牌即“八仙过海”，直接满贯自摸（花糊）。
- 可以吃（只能吃上家）、碰、明杠、暗杠、补杠，杠后补牌。补杠可以被抢杠。
- 截糊：一张牌多人可和时，只有离出铳者下家最近的一位和牌（不能一炮多响）；和 > 碰/杠 > 吃。
# 番种
- 鸡和 0、平和 1、对对和 3、混一色 3、清一色 7、小三元 5、大三元 8、小四喜 6（选项可改为满贯）。
- 满贯番种：字一色、大四喜、十三幺、九莲宝灯、坎坎和（四暗刻）、天和、地和、八仙过海。
- 附加番：门前清 1、自摸 1、无花 1、正花（与自己门风对应的花）1、一台花（集齐春夏秋冬或梅兰竹菊）2、三元牌刻 1、门风刻 1、圈风刻 1、海底捞月 1、杠上开花 1、抢杠 1。
- 番数超过选项“满贯番数”（8 / 10 / 13 番）时按满贯计。选项“起和番”：鸡和可和 / 1 番 / 3 番（默认 3 番起和），不够番不能和牌。
# 计分（半辣上）
- 番数对应的分：0 番 2、1 番 4、2 番 8、3 番 16、4 番 32、5 番 48、6 番 64、7 番 96、8 番 128、9 番 192、10 番 256、11 番 384、12 番 512、13 番 768。
- 出铳：出铳者一人付全数。自摸：其他三家各付一半。
- 包自摸（可关）：有人碰/杠了别人打出的第三组三元牌（或第四组风牌）后，若他自摸大三元（大四喜），由喂牌者独付三家的份额。
- 杠牌不另外计分；流局（荒庄）不计分。
# 庄家与局数
- 庄家和牌或流局连庄；闲家和牌则由下家坐庄，庄家轮完一圈后圈风前进（东→南→西→北）。
- 选项“圈数”：1 圈（东风圈）/ 4 圈（全庄）。最后一圈的最后一位庄家下庄时结束；为防止无限连庄，另有局数上限（每圈 16 局）。
- 每局结束后所有人点“继续”进入下一局。结束时按总分排名，同分并列。
