const String mcrRules = '''
# 牌与流程
- 4 人，144 张牌：万筒条各 1~9、东南西北中发白各 4 张，另有春夏秋冬梅兰竹菊 8 张花牌。每人 13 张，庄家先摸。
- 摸到花牌立即亮出并从牌墙尾补牌（补花），花牌每张计 1 番，但不计入起和番数。
- 可以吃（只能吃上家）、碰、明杠、暗杠、补杠；杠后从牌墙尾补牌。补杠时其他人可以抢杠和。
- 多家同时要一张牌：和 > 碰/杠 > 吃；多家同时和牌时离放铳者下家最近的一家优先（截和），不能一炮多响。
# 和牌与番种
- 和牌型：4 组面子 + 1 对将，或七对、十三幺、全不靠、七星不靠、组合龙等特殊型。
- 采用《中国麻将竞赛规则》81 种番型：88 番（大四喜、大三元、绿一色、九莲宝灯、四杠、连七对、十三幺）、64 番（清幺九、小四喜、小三元、字一色、四暗刻、一色双龙会）、48/32/24/16/12/8/6/4/2/1 番各档（清一色 24、七对 24、清龙 16、花龙 8、碰碰和 6、混一色 6、平和 2、断幺 2、门前清 2、自摸 1、边张/坎张/单钓将 1 等）。
- 计番按规则的互斥关系处理（例如大三元不再计箭刻、七对不再计门前清），不重复计番；有多种拆法时自动取番数最高的一种。
- 起和：除花牌外至少 8 番才能和牌（8 番起和）；无番和（8 番）也可和。
# 计分
- 点和：放铳者付 8 + 番数，其他两家各付 8 分。
- 自摸：其他三家各付 8 + 番数。
- 杠牌不另外计分；荒庄（牌摸完无人和）不计分。
# 局数与名次
- 选项“局数”：4 局（东风圈）/ 8 局 / 16 局（全庄，东南西北四圈）。每局庄家都轮到下家（不连庄），每 4 局换一次圈风。
- 每局结束后所有人点“继续”进入下一局。全部局数打完后按总分排名，同分并列。
''';

