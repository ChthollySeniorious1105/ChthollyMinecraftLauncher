const _csRules = '''
# 长沙麻将
4 人，只用万、筒、条共 108 张，无字牌、无花牌。可吃（仅上家）、碰、杠。庄家 14 张先出牌。
# 起手胡（开局亮牌，立即收分，不影响后续继续打）
- 大四喜：起手有 4 张相同的牌（每组算 1 个）。
- 板板胡：起手没有任何 2、5、8。
- 缺一色：起手缺少万/筒/条中的一门。
- 六六顺：起手有 2 个刻子（4 个刻子算 2 个）。
- 每个起手胡由其余三家各付 2 分。可选择“亮牌”或“不亮”。可在选项中关闭。
# 胡牌
- 小胡（平胡）：4 组顺子/刻子 + 1 对将，将必须是 2、5、8。
- 大胡（不需要 258 将）：碰碰胡、将将胡（全部是 2/5/8，任意组合即可胡）、清一色、七小对（豪华七小对算 2 个大胡，双豪华算 3 个）、全求人（四副全吃碰明杠，单钓点炮）、海底捞月/海底炮（最后一张）、杠上开花、杠上炮、抢杠胡、天胡、地胡。多个大胡叠加计数。
# 杠：补张与开杠
- 补张：像普通杠，从牌尾补一张，继续出牌。
- 开杠：必须杠后仍听牌。开杠后翻出牌尾 2 张：能胡则“杠上开花”；否则这两张视为打出，其他人可胡（杠上炮）。开杠后手牌锁定，以后只能摸什么打什么。
# 计分
- 小胡：点炮者付 1 分；自摸每家付 2 分。
- 大胡：每个大胡 6 分，点炮者付，自摸三家各付。
- 庄闲：庄家参与的每笔支付 +1 分。
- 扎鸟：胡牌后从牌尾翻 N 只鸟（1/2/4），按点数从庄家起逆时针数（1、5、9 为庄家，2、6 下家…）。鸟落在赢家或付款人位置，该笔支付翻倍（每中一鸟再加一倍）。
- 只能自摸：不能点炮胡，抢杠、杠上炮也不成立。
- 一炮多响：多家都可胡同一张时一起胡，下局由点炮者坐庄。
# 庄家与局数
胡牌者下局坐庄（一炮多响则点炮者坐庄），流局庄家连庄。共 4/8 局，结束后按累计分数排名。
''';

