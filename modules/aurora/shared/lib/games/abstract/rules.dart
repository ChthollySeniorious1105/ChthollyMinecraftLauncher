const backgammonRules = '''
# 概述
- 两人对弈。座位0 执白、座位1 执黑，各有 15 枚棋子，沿 24 个点逆向绕盘，把全部棋子移入己方内盘后再逐一移出（bear off），先移完者赢得本局。
- 比赛采用多局累计分制（选项“比赛分数”：1/3/5/7 分），先累计达到目标分的一方赢得整场比赛。

# 开局
- 每局开始双方各掷一颗骰子，点数大者先行，并直接使用这两颗骰子的点数走第一步；点数相同则重掷。

# 行棋
- 每回合掷两颗骰子，每颗骰子的点数分别让一枚棋子前进相应点数；掷出双数（如 4-4）则可走四次。
- 不能落在对方有 2 枚及以上棋子的点（被封锁的点）。
- 落在对方只有 1 枚棋子的点（散子）即“打”掉它，被打的棋子放到中柱（bar）。
- 中柱上有己方棋子时，必须先把它们从对方内盘重新入场，才能走其他棋子。
- 必须尽可能用完所有骰子；若两颗骰子只能用其中一颗，则必须使用点数较大的那颗。
- 全部 15 枚棋子都进入己方内盘后才能移出；点数恰好可移出，点数更大时只有在更高点位已无己方棋子时才可以用它移出最远的子。
- 回合内可以“撤销”重走本回合已走的步，走完后点“确认”结束回合（骰子全部用完时自动确认）。

# 计分
- 单胜：输家已移出至少一枚棋子，得 1 × 加倍骰数值。
- 全胜（gammon）：输家一枚都未移出，得 2 倍。
- 大全胜（backgammon）：输家一枚未移出，且仍有棋子在中柱或在赢家内盘，得 3 倍。

# 加倍骰（选项“加倍骰”）
- 轮到自己掷骰前，可以提出加倍；对手可“接受”（赌注翻倍，加倍骰归接受方所有，此后只有拥有者可以再加倍）或“拒绝”（立即输掉本局，按当前赌注计分）。
- 1 分制比赛不使用加倍骰；若加倍对自己已无意义（当前分数加赌注已达到目标分）则不能加倍。
- 克劳福德规则（选项）：当任意一方第一次达到“差 1 分获胜”时，紧接着的那一局双方都不能加倍，之后各局恢复。

# 其他
- 认输：认输方直接输掉整场比赛。
- 本实现不支持求和与悔棋（骰子在对局中随机产生，悔棋会被用来重掷）；不使用 Jacoby 规则、Beaver 等附加规则。
''';

const mancalaRules = '''
# 概述
- 两人对弈的播棋（Kalah 规则）。棋盘每方 6 个小坑和 1 个仓（位于己方右侧），开局每个小坑放入相同数量的石子（选项“每坑石子”：3/4/6 颗），仓为空。随机决定先手。

# 播种
- 轮到你时，选择己方一侧一个有石子的小坑，拿起其中全部石子，按逆时针方向每个坑放一颗，经过己方仓时也放一颗，但跳过对方的仓。
- 最后一颗石子落入己方仓：你再走一次（可以连续多次）。
- 吃子（选项“吃子规则”开启时）：最后一颗石子落入己方一个原本为空的小坑，且正对面的对方小坑中有石子，则把对面的石子连同这颗石子一起放入己方仓。关闭吃子规则时没有这一步。

# 结束与计分
- 任意一方的 6 个小坑全部为空时，对局立即结束；另一方小坑中剩余的石子全部归入其所有者的仓。
- 仓中石子多者获胜；数量相同为平局。

# 其他
- 认输：认输方判负。
- 求和：双方同意即以和棋结束。
- 悔棋：支持（本游戏除先手外没有随机因素）。
- 与常见规则的差异：落入空坑而对面也为空时不吃子，该石子留在原坑。
''';

const connect6Rules = '''
# 概述
- 两人对弈，19×19 棋盘，黑白双方轮流在交叉点上落子（开局随机决定谁执黑）。
- 黑方第一手只下 1 子，此后双方每回合各下 2 子（两子可放在任意空点，不必相连）。

# 胜负
- 任意方向（横、竖、两条斜线）连续同色棋子达到 6 个或以上即获胜，长连同样算赢；一回合中下第一子就连成六子也立即获胜。
- 棋盘下满仍无人连成六子则为和棋。

# 其他
- 没有禁手，没有提子，棋子落下后不再移动。
- 界面会标出对手上一回合落下的两子和本回合你已落下的子。
- 认输：认输方判负。
- 求和：双方同意即以和棋结束。
- 悔棋：支持，悔棋以单颗棋子为单位回退。
- 与五子棋的差异：每回合两子使先手优势大幅减小，因此不需要禁手规则；常用战术是同时制造两个“活四”级别的威胁让对方两子也挡不住。
''';

const hexRules = '''
# 概述
- 两人对弈，菱形六角格棋盘（选项“棋盘大小”：11×11 或 13×13）。开局随机决定红方，红方先行。
- 红方的目标是用一条连续的红色棋子链连接棋盘上下两条边；蓝方的目标是连接左右两条边。
- 每格与周围 6 个格相邻，双方轮流在任意空格放一子，棋子落下后不再移动或被吃。

# 交换规则（选项）
- 为了抵消先手优势，开启交换规则后：红方下完第一手，蓝方可以选择“交换”——双方互换颜色，第一手那颗子保留为红子，选择交换的一方改执红（不再落子，轮到新的蓝方下）。
- 因此先手一方的第一手不宜太强也不宜太弱；不交换则照常继续。

# 胜负
- 先连通自己两条边的一方获胜。
- 六角棋在数学上不可能出现和棋：棋盘下满时必然恰有一方连通。
- 界面会高亮获胜的连接路径。

# 其他
- 认输：认输方判负。
- 求和：虽然对局中不会自然产生和棋，但双方同意时仍可以和棋结束。
- 悔棋：支持（包括撤回交换）。
- 常用技巧：“桥”（两子隔一格斜对、中间有两个公共空格）几乎无法被切断，是连接的基本单位。
''';

const ninemenRules = '''
# 概述
- 两人对弈的九子棋（Nine Men's Morris，又称直棋、莫里斯棋）。棋盘由三个同心方框和四条连线组成，共 24 个点。每方 9 枚棋子，开局随机决定先手。

# 第一阶段：放子
- 双方轮流把手中的棋子放到任意空点，直到 9 枚全部放完。

# 第二阶段：走子
- 棋子全部放完后，轮到你时必须把己方一枚棋子沿线移动到相邻的空点。
- 飞子（选项“剩三子可飞”开启时）：某一方只剩 3 枚棋子时，他的棋子可以移动到棋盘上任意空点。关闭该选项时始终只能走相邻点。

# 三连与吃子
- 无论放子还是走子，只要新落下的棋子与同一直线上另外两枚己方棋子组成“三连”（mill），就立即移除对方一枚棋子。
- 不能移除处于三连中的对方棋子，除非对方所有棋子都在三连中。
- 把棋子移出三连再移回来可以再次形成三连并吃子。

# 胜负
- 一方棋子少于 3 枚（只剩两子）时判负。
- 走子阶段轮到某方时，他没有任何合法的移动，判负。
- 和棋：放子结束后同一局面（同一方行棋）第三次出现；或全局达到 200 手仍未分胜负。
- 认输：认输方判负。求和：双方同意即以和棋结束。悔棋：支持。
''';
