const tetrisRules = '''
# 概述
- 2~4 人实时对战，采用 TETR.IO 多人规则。每人一块 10 列 × 20 行的场地（上方还有 20 行隐藏缓冲区）。
- 开局 3 秒倒计时，之后方块按重力自动下落。把横行填满即可消除；消行会向对手发送垃圾行。坚持到最后的玩家获胜。

# 方块与操作
- 7-bag 出块：每 7 块里 I J L O S T Z 各出现一次，所有玩家的方块序列相同。可看到后 5 块预览。
- 左/右移动，按住（DAS）移到墙边；顺时针、逆时针、180° 旋转（SRS 踢墙表，180° 用 TETR.IO SRS+ 踢墙）。
- 软降（逐格下落，每格 +1 分）、瞬降到底（不锁定）、硬降（直接落地锁定，每格 +2 分）。
- 暂存（Hold）：把当前块存起来换出暂存块，每块只能用一次。
- 方块着地后有 0.5 秒锁定延迟，着地期间移动/旋转可重置延迟，最多 15 次（下落到新的最低行时重新计数）。

# 攻击（送出的垃圾行数）
- 单消 0、双消 1、三消 2、四消（Quad）4。
- T-Spin：最后一个动作是旋转，且 T 中心四角有 ≥3 格被占。T-Spin 单/双/三消分别 2/4/6；Mini T-Spin 单 0、双 1。
- B2B（背靠背）：连续的四消或旋转消行额外 +1 起，链越长加成越高（最高 +7）。普通消行会打断 B2B。
- 连击：连续每块都消行，攻击按 (1 + 0.25 × 连击数) 放大；全消（Perfect Clear）额外 +10。
- 开局 3 分钟后进入加时，垃圾倍率每秒 +0.008。

# 垃圾行
- 收到的攻击先进入等待槽（约 0.33 秒后生效）。你自己消行送出的攻击会先抵消等待槽中的垃圾，剩余部分才打给对手。
- 放下一块且没有消行时，已生效的垃圾最多 8 行从底部升起。每次攻击的垃圾行共用一个缺口列，相邻两次攻击的缺口不同。

# 选项
- 起始速度：1 / 4 / 8 级。之后每消 10 行 +1 级，每过 1 分钟 +1 级，重力随等级加快。
- 攻击目标：随机——每次从存活对手中随机选一人；反击——优先打最后一个攻击你的人。

# 出局与胜负
- 新方块出生位置被占（Block Out）、方块整个锁定在可见区之上（Lock Out）、或垃圾行把方块顶出缓冲区顶部，即出局；最后一次攻击你的人记一次 KO。
- 认输视同出局，且排名在所有未认输玩家之后。
- 只剩一人存活时结束，存活者第一；其余按出局先后排名（越晚出局越靠前），同时出局按分数。10 分钟安全上限到时，存活者按分数排名。
- 分数：消行基础分 × 等级（B2B 再 ×1.5），另有连击、全消、T-Spin 与下落加分，只用于同时出局/时间到的排名。
''';

const snakeRules = '''
# 概述
- 2~6 人在同一张 30×30 地图上实时对战，每秒约 6 步，开局约 2 秒倒计时。
- 每条蛇初始长度 3，从地图四周出发朝向中央。地图上始终保持（人数 + 3）个食物。

# 操作
- 选择上/下/左/右，新方向在下一步生效。不能直接掉头（与当前方向相反的操作会被忽略）；一步之内以最后一次输入为准。
- 掉线的玩家会由电脑自动驾驶，重新操作后恢复手动。

# 规则
- 吃到食物长度 +1，新食物会随机出现在空地上。
- 撞墙、撞到任何蛇的身体（包括自己）即出局。蛇尾在这一步会移开的格子可以安全进入（除非该蛇这一步正好吃到食物）。
- 两个蛇头同时进入同一格（迎头相撞）或互相交换位置，双方同归于尽。
- 出局的蛇会隔一格变成一个食物（全图食物上限 60 个），供其他人抢食。

# 胜负
- 只剩一条蛇存活时立即结束，它获得第一；全部同时出局则按长度排名。
- 时间到时，存活的蛇按长度排名，都排在已出局者前面。
- 已出局者按出局先后排名：越晚出局越靠前，同时出局按长度。
- 认输视同立即出局，且排在所有未认输玩家之后；如果只剩一名玩家未认输，对局立即结束。

# 选项
- 时长：2 / 3 / 5 分钟，到时按上面的规则结算。

# 电脑
- 电脑会寻路去吃最近的食物，并避开可能被困住的死路。简单难度常常走错路、不注意对手的蛇头；困难难度会判断食物是否会被别人抢先，并留出更大的活动空间。
''';

const minesweeperRules = '''
# 概述
- 2~6 人竞速扫雷。所有人拿到同一张雷图，但各扫各的，别人看不到你的盘面（只能看到进度百分比）。
- 目标是翻开全部非雷格子，最先完成的玩家获胜，对局立即结束。

# 操作
- 翻开：翻开一格。数字表示周围 8 格中雷的数量；数字为 0 时会自动连片翻开。
- 插旗 / 取消旗：标记你认为是雷的格子，插旗的格子不能直接翻开。
- 双击数字（Chord）：当周围旗子数与该数字相等时，一次翻开周围所有未翻开的格子；旗子插错会踩雷。
- 每人的第一次点击必定安全，并且一定是 0（周围的雷会被移到别处，仅影响你自己的盘面，类似 Windows 扫雷）。

# 选项
- 难度：初级 9×9 共 10 颗雷（时限 5 分钟）；中级 16×16 共 40 颗雷（时限 10 分钟）；高级 30×16 共 99 颗雷（时限 15 分钟）。
- 踩雷：出局——踩雷后立即出局，保留当前进度参与排名；罚时 10 秒——踩到的雷会显示出来，每颗计 10 秒罚时，可继续游戏，完成用时 = 实际用时 + 罚时。

# 胜负与排名
- 有人扫完时对局结束：完成者第一；其余玩家按翻开的格子数排名，翻开数相同时未出局者在前，再比罚时。
- 所有人都出局，或时限到时，按翻开的格子数排名（规则同上）。
- 认输视同出局，且排在所有未认输玩家之后；如果只剩一名玩家未认输，对局立即结束，该玩家获胜。

# 电脑
- 电脑只根据自己盘面上的数字推理：确定安全就翻开，确定是雷就记下，无法推理时才猜。简单难度推理较少、经常乱猜；困难难度会估算每格是雷的概率，挑最安全的格子猜。
''';

const battle2048Rules = '''
# 概述
- 2~4 人同时进行 2048，每人一块 4×4 棋盘，没有回合，各自尽快滑动。
- 所有人的新方块序列相同（第 N 次出块的位置选择与数值对每个人都一样），运气公平。

# 操作与合并
- 向上/下/左/右滑动：所有方块朝该方向移动到底，相邻两个相同数字合并成它们的和，每个方块一次滑动只合并一次。
- 合并得到的数值计入分数。滑动后若棋盘有变化，会在随机空格出现一个新方块（90% 为 2，10% 为 4）；没有任何变化的方向不能滑动。

# 石块攻击（可选）
- 开启时，每合成出一个 128 或更大的方块，就给每位仍能行动的对手扔 2 个石块。
- 石块会在对手下一次滑动后落在其随机空格上，占据空间；石块相当于一个 2，可以与 2 或另一个石块合并成普通的 4，这样就能消掉它。

# 结束与胜负
- 某人的棋盘四个方向都不能滑动时即“无路可走”，该玩家停止，但分数保留。
- 所有人都无路可走，或时间到时，对局结束。按分数排名，分数相同比最大方块，再相同则并列。
- 认输视同无路可走，且排在所有未认输玩家之后；如果只剩一名玩家未认输，对局立即结束。

# 选项
- 石块攻击：开启 / 关闭。
- 时长：2 / 3 / 5 分钟。

# 电脑
- 电脑用期望搜索（expectimax）评估每个方向，偏好空格多、数字单调排列、最大块在角落的局面。简单难度经常随手乱滑；困难难度会多看一步。
''';

const sudokuRules = '''
# 概述
- 1~6 人竞速数独。所有人拿到同一道标准 9×9 数独，保证有唯一解，各填各的，别人只能看到你的进度。
- 规则：每行、每列、每个 3×3 宫中 1~9 各出现一次。题目给出的数字不能修改。

# 操作
- 选中空格填入 1~9。填入的数字会立即判定：正确就固定在格子里；错误不会写入，并记一次失误。
- 笔记模式：在格子里记录候选数字，仅自己可见，不会判定对错。

# 选项
- 难度：简单约 40 个提示数、中等约 32 个、困难约 25 个（在保证唯一解的前提下尽量接近）。
- 失误上限：3 次出局 / 5 次出局 / 不限。达到上限即出局，不能再填，保留已填进度参与排名。

# 胜负与排名
- 最先把所有空格填对的玩家获胜，对局立即结束。
- 其余玩家：未出局者排在出局者之前，再按填对的格数排名，格数相同比失误次数（少者在前）。
- 所有人都出局或 30 分钟时限到，按同样的规则排名。
- 认输视同出局，且排在所有未认输玩家之后；如果只剩一名玩家未认输，对局立即结束。单人游戏认输即结束。
- 结束后所有人都能看到完整答案。

# 电脑
- 电脑只看自己的盘面，用“唯一候选数”和“隐性唯一数”逐格推理，推不出时才从答案推算。电脑按固定节奏填数，偶尔会填错一次（不会因此出局）。简单难度更慢、更容易填错；困难难度更快且不会填错。
''';
