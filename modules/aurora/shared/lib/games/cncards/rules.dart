const String bigtwoRules = '''
# 概述
- 2~4 人，使用一副 52 张牌（无大小王）。先出完手牌者赢得本局，其余玩家按剩余张数扣分。
- 4 人每人 13 张；3 人每人 17 张，第 52 张额外发给持有♦3 的玩家；2 人每人 13 张，其余 26 张不用（谁也看不到）。

# 大小
- 点数：3 < 4 < … < K < A < 2；花色：♦ < ♣ < ♥ < ♠。单张先比点数再比花色，♠2 最大。
- 对子比较其中较大的那张；三条比较点数。

# 牌型
- 单张、对子、三条、五张牌型。四张牌不能单独出（铁支必须带一张凑成五张）。
- 五张牌型从小到大：顺子 < 同花 < 葫芦（三带二）< 铁支（四带一）< 同花顺。
- 顺子按自然点数连续，A2345 最小、10JQKA 最大，JQKA2 等“绕圈”不算顺子；同样大小的顺子比最大那张的花色。
- 同花按最大牌依次比较；葫芦比三张部分；铁支比四张部分。

# 流程
- 持有全场最小牌（通常是♦3；2 人局时可能是别的牌）的玩家先出，第一手必须包含这张牌。
- 之后按座位顺序出牌，必须出相同张数且更大的牌，也可以“不要”。其余人都不要时，最后出牌者重新自由领出任意牌型。
- 有人出完即本局结束。有人只剩一张时系统会提示。

# 计分
- 每位输家扣“剩余张数 × 倍数”，全部给赢家。
- 选项“剩牌翻倍”开启时：剩 10~12 张 ×2，剩 13 张及以上 ×3；关闭时一律 ×1。
- 选项“局数”：打满设定局数后按累计积分排名（并列同名次）。

# 其他
- 两人对局可以认输，对手直接获胜。
- 与常见港式规则的差异：没有“炸弹”压制不同张数的规定，也没有“报单必须顶大”的强制规则（电脑会自行注意）。
''';

const String zhajinhuaRules = '''
# 概述
- 2~9 人，每人 3 张暗牌，初始 1000 筹码，底注 10。每局开始每人先交底注，由庄家下家开始按顺序行动，庄家每局轮换。
- 牌型从大到小：豹子（三张同点）> 顺金（同花顺）> 金花（同花）> 顺子 > 对子 > 散牌。
- 同牌型比点数（A 最大）；对子先比对子再比单张；A23 是最小的顺子，AKQ 最大。花色不分大小，完全相同算平。

# 闷牌与看牌
- 不看牌（闷牌）时跟注只需付当前单注；看过牌后跟注、加注都要付双倍。任何时候都可以看牌，看牌不消耗行动。
- 单注档位 10 / 20 / 30 / 50 / 100。加注只能加到更高的档位，此后所有人按新单注跟。

# 行动
- 跟注：付当前单注（看牌者 ×2）。
- 加注：提高单注并付新单注。
- 弃牌：放弃本局，已下的筹码留在底池。
- 比牌：第一轮不能比牌（筹码不够跟注时例外）。花费为跟注价的两倍，与任一在局玩家比大小，输者出局；点数完全相同时发起者输。比过牌的双方互相看到对方的牌。
- 只剩一人时他赢得全部底池。

# 选项
- 局数：打满设定局数结束；中途只剩一名有筹码的玩家也会提前结束。筹码输光即出局。
- 封顶轮数：下注超过设定轮数后强制所有在局者开牌，最大者赢得底池，并列平分。
- 235 吃豹子：开启后杂色 2、3、5 可以赢豹子（但仍输给其他所有牌型）；关闭时 235 就是普通散牌。

# 胜负
- 结束时按筹码多少排名，并列同名次。两人对局可以认输，对手直接获胜。
''';

const String douniuRules = '''
# 概述
- 2~8 人，每人 5 张牌。闲家各自与庄家比牌，不和其他闲家比。
- 点数：A 为 1，2~9 按面值，10、J、Q、K 都算 10。

# 牌型
- 从 5 张里选 3 张凑成 10 的倍数，剩下 2 张点数相加取个位数就是“牛几”；个位为 0 即“牛牛”；找不到 3 张凑整则为“没牛”。系统自动选最优组合。
- 特殊牌型（选项开启时），从大到小：五小牛（5 张都小于 5 且总点数 ≤ 10）> 炸弹牛（四张同点）> 五花牛（5 张都是 J/Q/K）> 牛牛。
- 牌型相同时比最大的一张：按点数（A 最小、K 最大），同点再比花色 ♠ > ♥ > ♣ > ♦。炸弹牛比炸弹的点数。没有平局。

# 流程
- 抢庄模式：发牌后每人选择不抢或抢 1~4 倍，倍数最高者当庄（同倍数随机），庄家倍数计入输赢；无人抢庄时随机一人当庄，倍数 ×1。
- 轮流坐庄模式：按座位轮流当庄，庄家倍数固定 ×1。
- 明牌选项：开启时抢庄与下注阶段可以先看自己的前 4 张牌；关闭时摊牌前完全看不到自己的牌。
- 闲家下注 1~5 倍，然后所有人摊牌结算。

# 计分
- 每位闲家与庄家结算：输赢 = 胜方牌型赔率 × 闲家下注倍数 × 庄家抢庄倍数。
- 经典赔率：没牛~牛六 ×1，牛七~牛九 ×2，牛牛 ×3，五花牛 ×4，炸弹牛 ×5，五小牛 ×6。
- 疯狂赔率：没牛、牛一 ×1，牛二~牛九 按牛几赔几倍，牛牛及特殊牌型 ×10。
- 局数：打满设定局数后按累计积分排名，并列同名次。两人对局可以认输，对手直接获胜。
