const String shisanshuiRules = '''
# 概述
- 2~4 人，每人 13 张，自己摆成三墩：前墩 3 张、中墩 5 张、后墩 5 张。所有人理好牌后同时亮牌，与每位对手两两比较。
- 必须满足 后墩 ≥ 中墩 ≥ 前墩，否则“倒水”。本实现提交时会拒绝倒水的摆法，只有强制提交才按倒水结算（电脑总是摆出合法牌型）。

# 牌型
- 五张墩从大到小：同花顺 > 铁支 > 葫芦 > 同花 > 顺子 > 三条 > 两对 > 对子 > 乌龙。前墩只有三条、对子、乌龙。
- 同牌型比点数（A 最大，A2345 是最小的顺子），花色不分大小。前墩与中墩用同一标准比较（前墩三条可以和中墩三条比）。

# 比牌计分（两两之间）
- 每墩赢者得分、输者失分，平局 0 分。一般每墩 1 分。
- 加分墩：前墩三条（冲三）3 分；中墩葫芦 2 分、铁支 8 分、同花顺 10 分；后墩铁支 4 分、同花顺 5 分。
- 打枪：一方三墩全胜，与该对手之间的得分翻倍。
- 倒水者对每位未倒水的对手三墩全输（按对方墩的分值计），并视为被打枪。
- 全垒打（选项，至少 3 人）：打枪了所有其他玩家时，与每人之间的得分再翻倍。

# 特殊牌型（选项）
- 按整手 13 张自动判定，与摆法无关：至尊清龙（同花一条龙）26 分、一条龙（A~K 各一张）13 分、六对半 3 分、三同花（能分成 3/5/5 张三组同花）3 分、三顺子（能分成三组顺子）3 分。
- 有特殊牌型的一方直接从每位没有特殊牌型的对手处得到对应分数，不再逐墩比较；双方都有时大者赢取其分值，相同则不计分。

# 胜负
- 选项“局数”：打满后按累计积分排名，并列同名次。两人对局可以认输，对手直接获胜。
