const bombermanRules = '''
# 概述
- 2~4 人在同一张 15×13 的竞技场里实时对战（四周是围墙，内部 13×11 可走）。开局约 2 秒倒计时。
- 竞技场里横纵坐标都为偶数的格子是打不坏的石柱，其余空地上随机铺满可以炸毁的砖块；四个角落的出生点及其相邻格子保证是空的。
- 目标：用炸弹炸开道路、收集道具，并把对手炸飞。最后存活的玩家获胜。

# 操作
- 移动：方向键 / WASD，手机上用屏幕方向键。按住一直走，轻点走一格。
- 放炸弹：空格键 / 回车，手机上点「炸弹」按钮。炸弹放在你当前所在的格子。
- 掉线的玩家由电脑自动操作，重新操作后恢复手动。

# 炸弹
- 炸弹约 2.5 秒后爆炸，火焰呈「十」字形向上下左右延伸，长度等于放置时的火力。火焰持续约 0.5 秒，期间进入火焰同样会被炸飞。
- 火焰遇到石柱停止；遇到砖块会把砖块炸掉并停在那里；遇到地上的道具会把道具烧掉。
- 火焰波及其他炸弹时会立刻引爆它（连锁爆炸）。
- 炸弹会挡路：放下后任何人都不能走进炸弹所在的格子（刚放下时自己站在上面，可以离开）。
- 同时在场的炸弹数不能超过你的炸弹上限，炸弹爆炸后返还。

# 道具
- 砖块被炸毁时约有三分之一几率掉落道具，走上去即可拾取：
- 💣 炸弹 +1：可同时放置的炸弹数 +1（最多 8）。
- 🔥 火力 +1：火焰长度 +1（初始 2，最多 8）。
- 👟 速度 +1：移动更快（最多 +2 级）。

# 胜负与排名
- 被火焰（包括自己的炸弹）碰到即出局。炸飞别人记 1 次击杀，自爆不计。
- 只剩一人存活时立刻结束，存活者第一。全部同时出局则按击杀数排名。
- 时间到时：存活的玩家都排在出局者前面，彼此之间按击杀数排名（相同则并列）。
- 出局的玩家按出局先后排名：越晚出局越靠前，同时出局按击杀数。
- 认输视同立即出局，且排在所有未认输玩家之后。

# 选项
- 时长：2 / 3 / 5 分钟。
- 砖块密度：稀疏 / 普通 / 密集，影响开局时砖块的数量。

# 电脑玩家
- 电脑会计算所有炸弹（含连锁）的危险区域并躲避，只在确认有退路时才放炸弹。
- 简单难度会犹豫、偶尔不看退路乱放炸弹；困难难度会主动追击玩家。
''';

const dobbleRules = '''
# 概述
- 2~8 人实时抢答的观察力游戏（Dobble / Spot It!）。共 57 张圆形卡牌，每张牌上有 8 个大小、角度各不相同的图案。
- 神奇之处：任意两张牌之间，有且只有一个相同的图案（本实现用 7 阶有限射影平面生成整副牌，共 57 种图案）。
- 每一轮大家同时比较「自己的牌」和「中央的牌」，谁先在自己的牌上点中那个唯一相同的图案，谁就赢下这一轮。

# 操作
- 直接点击你自己牌上的图案。点对了立刻赢下这一轮；点错了会被冻结约 1.5 秒，期间不能再点。
- 每轮结束后有约 1.4 秒的展示时间，高亮显示赢家和相同的图案，然后进入下一轮。
- 慢了一步（别人已经抢到）的点击无效，不受惩罚。

# 模式一：塔楼（默认）
- 每人先发 1 张牌，正面朝上作为「你的牌」；剩下的牌组成中央牌堆，最上面一张翻开。
- 找到你的牌与中央牌的相同图案并点中，就把中央这张牌收入你的牌堆——它成为你新的「你的牌」，中央翻开下一张。
- 中央牌堆被抢完时游戏结束，收集牌最多的人获胜（相同则并列）。

# 模式二：深井
- 先翻 1 张牌放在中央，其余牌平均发给所有人（除不尽的牌不用），每人只能看到自己牌堆最上面一张。
- 找到你最上面的牌与中央牌的相同图案并点中，就把你的这张牌打到中央，成为新的中央牌；你露出下一张牌。
- 最先把自己的牌全部打出的人获胜；其余玩家按剩余牌数从少到多排名。

# 其他规则
- 认输的玩家不能再参与抢答，排在所有未认输玩家之后；只剩一名玩家时游戏结束。
- 掉线的玩家由电脑代为抢答，重新操作后恢复手动。

# 电脑玩家
- 电脑的反应时间由房间的电脑难度决定：简单约 4~8 秒且经常点错；普通约 2~5 秒，偶尔点错；困难约 1.3~3 秒，从不点错。
''';
