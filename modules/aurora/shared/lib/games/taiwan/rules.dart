/// Rules text (GameDef.rules) for 台湾十六张.
library;

const String taiwanRules = '''
# 牌与流程
- 4 人，144 张牌：万筒条 1~9、东南西北中发白各 4 张，另有春夏秋冬梅兰竹菊 8 张花牌。每人 16 张，庄家先摸第 17 张。
- 胡牌型为 5 组面子（顺子/刻子/杠）+ 1 对将，共 17 张。没有七对、十三幺等特殊牌型。
- 摸到花牌立即亮出并从牌尾补牌。牌墙最后留 16 张（8 墩）不摸，摸到留牌时流局（荒庄）。
- 可以吃（只能吃上家）、碰、明杠、暗杠、补杠，杠后补牌；补杠可以被抢杠。多人同时胡一张牌时，离放枪者下家最近的一位胡（截胡）；胡 > 碰/杠 > 吃。
- 没有起胡台数限制，凑成牌型即可胡。
# 台数
- 庄家 1 台（庄家胡牌或庄家放枪/被自摸时计）；连庄拉庄：庄家连 N 局时再加 2N 台（连 N 拉 N）。
- 门清 1、自摸 1、门清自摸 3、全求人 2、海底捞月/河底捞鱼 1、杠上开花 1、抢杠 1。
- 花牌：正花（自己门风对应的花）每张 1、花槓（集齐一组四张）2；八仙过海（集齐 8 张）8、七抢一（自己 7 张时抢别人的 1 张）8，两者立即胡牌。
- 字牌：圈风刻 1、门风刻 1、三元牌刻 1；小三元 4、大三元 8、小四喜 8、大四喜 16。
- 牌型：碰碰胡 4、混一色 4、清一色 8、字一色 16、平胡 2（无花无字、全顺子、胡两面、非自摸）。
- 暗刻：三暗刻 2、四暗刻 5、五暗刻 8。独听（边张/中洞/单钓，只听一张）1。
- 天胡 16、地胡 16、人胡 8。
# 计分
- 每位付款人付：底 + 台数 × 每台。选项“底/台”：100/20（默认）、300/100、50/10。
- 放枪：放枪者一人付；自摸：其他三家各付。庄家的台（庄家 1 台 + 连庄拉庄 2N 台）只在庄家与付款人/胡牌者之间计算。
- 杠牌不另外计分；流局不计分。
# 连庄与终局
- 庄家胡牌或流局连庄，闲家胡牌则下家坐庄；四位庄家轮完一圈换圈风。
- 选项“圈数”：一圈（东风圈）或一将（四圈）。打完设定圈数结束（另有局数上限防止无限连庄）。
- 每局结束后所有人点“继续”进入下一局。结束时按总分排名，同分并列。
''';
