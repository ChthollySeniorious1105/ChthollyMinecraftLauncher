const gomokuRules = '''
# 概述
- 两人对弈，一方执黑、一方执白，黑棋先行。开局时系统随机决定谁执黑。
- 双方轮流在棋盘的空交叉点上落一子，落下后不能移动、不能提走。
- 先在横、竖或两条斜线任一方向上连成五子的一方获胜。

# 棋盘
- 选项“棋盘”：15 路（15×15，标准连珠棋盘）或 19 路（19×19，围棋棋盘）。
- 棋盘下满仍无人获胜则为和棋。

# 规则选项
- 自由（默认）：五连或更长的连子（长连）都算获胜，黑白双方都没有任何限制。
- 标准：必须恰好五连才获胜，六子及以上的长连不算胜（落下长连的一手不会结束对局，游戏继续）。黑白双方同样适用。
- 连珠禁手：只限制黑棋。黑棋落子形成“三三”（同时形成两个活三）、“四四”（同时形成两个四，包括同一条线上的两个四）或“长连”（六子及以上）即为禁手，黑棋直接判负。黑棋若在形成禁手的同时恰好连成五子，则五连优先，黑棋获胜。白棋没有禁手，白棋长连也算获胜。
- 连珠禁手规则下，轮到黑棋时界面会标出当前的禁手点，提醒黑方不要落在那里。
- 判断活三时只计算“真活三”：能够再走一步形成活四（两端都能成五的四）的三才算，两头被堵或成四点本身是禁手的三不算。

# 与常见规则的差异
- 本实现没有“三手交换”“五手两打”“Swap”等开局规则，也不指定开局，第一手可以下在任意位置。
- 没有时间限制，没有“必须先下天元”的要求。

# 胜负与名次
- 五连（按所选规则）的一方获胜，得第 1 名，对方第 2 名。
- 连珠规则下黑棋下出禁手：白棋获胜。
- 认输：轮到任何一方时都可以认输，对方直接获胜。
- 求和：双方都同意和棋时对局以和棋结束，双方并列第 1 名；棋盘下满也是和棋。
- 支持悔棋：同意后撤回最近的着法，局面精确恢复。

# 电脑难度
- 简单：经常随手乱下，不会算连续冲四。
- 普通：识别冲四、活三等棋形，会算连续冲四取胜（VCF），并做两层推演。
- 困难：在普通基础上扩大计算量，并检查对手在自己落子后是否有连续冲四的杀棋，提前防守。
''';

const othelloRules = '''
# 概述
- 黑白棋（又称奥赛罗、翻转棋），两人在 8×8 棋盘上对弈，黑棋先行，开局时随机决定谁执黑。
- 开局中央四格已摆好两黑两白（对角交叉摆放）。

# 落子与翻转
- 每一步必须落在空格上，并且要在横、竖、斜任一方向上“夹住”对方的棋子：新落的子与己方已有的某颗子之间，连续排列的全部是对方棋子。
- 所有被夹住的对方棋子（可以同时在多个方向）都翻转成己方颜色。
- 不能夹住任何对方棋子的位置不能落子。界面会提示当前所有合法落点。
- 若一方没有任何合法落点，则自动停一手（Pass），由对方继续下；对方仍可落子时本方不能主动放弃。

# 终局与计分
- 双方都无处可下时（通常是棋盘下满）对局结束。
- 统计双方棋子数，多者获胜；数量相等为和棋。
- 本实现不把空格计入胜方（比分即为双方实际子数）。

# 胜负与名次
- 子多的一方第 1 名，另一方第 2 名；和棋时双方并列第 1 名。
- 认输：任何时候都可以认输，对方直接获胜。
- 求和：双方都同意和棋时以和棋结束，并列第 1 名。
- 支持悔棋：局面完全由着法决定，可以撤回最近的着法。

# 小技巧
- 四个角一旦占据就永远不会被翻转，非常重要。
- 紧挨角的格（尤其斜对角的 X 位）容易把角送给对方，在角没被占时应谨慎。
- 前中盘让对方可下的位置少（行动力）往往比多吃子更重要。

# 电脑难度
- 简单：一半的时候随机落子，其余时间只看一步。
- 普通：按位置权重与行动力评估，迭代加深搜索约 5 层。
- 困难：更深的搜索与更长的思考时间，残局（剩余空格不多时）尽量算到终局精确比分。
''';

const connect4Rules = '''
# 概述
- 四子棋（Connect Four），两人对弈。棋盘竖直放置，共 7 列 6 行。
- 开局时随机决定先手，先手执红，后手执黄。

# 落子
- 双方轮流选择一列投下一枚棋子，棋子受重力作用落到该列最下方的空位。
- 已经放满 6 枚棋子的列不能再投。
- 棋子投下后不能移动。

# 胜负
- 先在横、竖或斜线方向上连成四枚（或更多）同色棋子的一方获胜，界面会高亮这条连线。
- 42 格全部放满仍无人连成四子，则为和棋。
- 获胜者第 1 名，对方第 2 名；和棋时双方并列第 1 名。
- 认输：随时可以认输，对方直接获胜。
- 求和：双方都同意和棋时以和棋结束，并列第 1 名。
- 支持悔棋：撤回最近的着法。

# 与常见规则的差异
- 与标准四子棋完全相同，没有“弹出（Pop Out）”等变体，没有时间限制。
- 先手是随机决定的（理论上完美对弈时先手必胜，所以随机先手更公平）。

# 小技巧
- 中间一列最有价值，能参与最多的四连。
- 注意对手的“双重威胁”：同时存在两个可以连四的位置时无法同时堵住。
- 不要在对手获胜点正下方的格子落子，否则会替对手“垫”出落点。

# 电脑难度
- 简单：大多数时候随机投子，偶尔只看两步。
- 普通：会立刻取胜或堵住对手，并用 alpha-beta 搜索约 9 层。
- 困难：搜索更深、思考时间更长，很少犯错。
''';

const dotsBoxesRules = '''
# 概述
- 点格棋（Dots and Boxes），2~4 人游戏。棋盘由点阵组成，相邻两点之间可以连一条边。
- 选项“棋盘”：3×3、4×4（默认）或 5×5 个格子。
- 开局时随机决定先手，之后按座位顺序轮流。

# 行动
- 轮到你时，在任意两个横向或纵向相邻、尚未连线的点之间画一条边。
- 如果你画的边正好补上了某个格子的第四条边，这个格子归你（标上你的颜色），并且你必须再画一条边。
- 一条边最多可以同时完成两个格子（两个格子都得分），同样再走一步。
- 没有完成格子时，轮到下一位玩家。
- 本实现中画边是强制的，不能放弃，也不能拒绝得分后继续画边。

# 终局与计分
- 所有边都画完时游戏结束，每个格子 1 分，得分最多者获胜。
- 名次按格子数排列，同分并列（例如两人并列第 1 名）。

# 认输与求和
- 认输：两人对局时认输方判负、对方获胜；三人及以上时，认输会直接结束本局，认输者为最后一名，其余玩家按当前格子数排名。
- 求和：所有真人都同意时以和棋结束，全体并列第 1 名。
- 支持悔棋：撤回最近的画边，局面精确恢复。

# 策略提示
- 不要轻易画一个格子的第三条边，否则下一位玩家可以直接拿走这个格子。
- 后期棋盘会形成若干“长链”，谁被迫先打开长链往往就会输掉大部分格子。
- 高手会用“让二”（double-dealing）的技巧：吃长链时故意留下最后两个格子给对手，以保持控制权。

# 电脑难度
- 简单：经常随手画边，送格子也不在意，有时还会漏吃。
- 普通：先吃能吃的格子，尽量不画第三条边，被迫送格子时送得最少，会用“让二”保持控制。
- 困难：在普通基础上，两人对局的残局（剩余边不多时）精确计算最优画法。
''';

const draughtsRules = '''
# 概述
- 跳棋（Draughts / Checkers），两人对弈，只在深色格上行棋。开局时随机决定谁执白，白方（在下方）先走。
- 选项“规则”：国际跳棋 10×10（每方 20 子）或英式跳棋 8×8（每方 12 子）。

# 走子
- 兵（普通棋子）每次向前斜走一格到空的深色格。
- 兵走到对方底线即升为“王”。
- 国际规则：王可以沿斜线飞行任意格（类似国际象棋的象）。英式规则：王只能斜走一格，但可以前后走。

# 吃子
- 斜向相邻有对方棋子且其后一格为空时，可以跳过去把它吃掉；落下后若还能继续吃，必须连跳到底。
- 有子必吃：只要有吃子的走法，就必须吃子，不能走普通步。
- 国际规则：兵可以向前也可以向后吃子；王可以飞吃（隔着若干空格吃掉斜线上的一个棋子，并落在其后任意空格上）；必须选择吃子数量最多的走法（最大吃子规则）；连跳过程中被吃的棋子到整步结束才移除，同一棋子不能被跳两次。
- 英式规则：兵只能向前吃子；有多种吃法时可以任选一种（不要求最多），但选定后必须跳完；兵在吃子中途到达底线升王时，本步立即结束。
- 连跳时要在界面上依次点击每个落点。

# 胜负
- 对方无子可走（棋子被吃光或全部被堵死）时获胜。获胜者第 1 名，对方第 2 名。
- 和棋（双方并列第 1 名）：同一局面（同一方走棋）重复出现三次；国际规则下连续 25 回合（50 步）双方都只走王且没有吃子；英式规则下 40 回合（80 步）没有吃子也没有兵的移动；总步数达到 300 步上限。
- 认输：随时可以认输，对方直接获胜。
- 求和：可以在棋盘上提议和棋，对方同意即和棋；平台的求和功能（所有真人同意）也可以直接和棋。
- 支持悔棋：撤回最近的着法。

# 电脑难度
- 简单：一半的时候随机走合法步，其余时间只看两步。
- 普通：alpha-beta 搜索约 6 层，吃子局面会继续延伸计算。
- 困难：更深的搜索与更长的思考时间。
''';
