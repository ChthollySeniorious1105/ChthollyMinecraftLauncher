const String _oldmaidRules = '''
# 抽乌龟
经典的合家欢纸牌游戏，适合 2～6 人。使用一副 52 张的扑克牌（不含大小王）。

# 准备
- 经典玩法（抽掉一张暗牌）：发牌前随机抽掉一张牌扣在一边，谁也不知道是什么。与它同点数的另外三张里，总会有一张配不上对，这张就是“乌龟”。
- 大王乌龟：在 52 张牌里加入一张大王，大王永远配不上对，谁最后拿着大王谁就是乌龟。
- 所有牌依次发给各位玩家，张数可能相差一张。
- 发完后每人自动把手里点数相同的两张牌配成一对打出（例如两张 7、两张 K）。三张同点只能打出一对，留下一张。

# 流程
- 从 1 号位开始，轮到你时，从下家（顺时针下一位还有牌的玩家）手里抽一张牌。对方的牌是背面朝上的，你只能点选一个位置，看不到牌面。
- 抽到的牌如果能和手里的牌配成一对，就自动打出；否则留在手里，并被随机插进你的手牌中。
- 被抽的玩家每次被抽后手牌会重新洗乱，所以记位置是没用的。
- 手牌出完的玩家“上岸”，安全退出，按上岸顺序排名次。
- 之后轮到下一位还有牌的玩家抽牌，抽牌对象也随之跳过已上岸的玩家。

# 胜负
- 最后只剩一名玩家手里还有牌（就是那张乌龟），他就是本局的乌龟，排最后一名。
- 其余玩家按上岸先后排名：第一个出完的是第一名。

# 信息
- 你只能看到自己的手牌，其他人只显示张数和已配对数；打出的对子是公开的。
- 抽牌后只有抽牌者和被抽者知道这张牌是什么。
- 游戏结束时公开所有剩余手牌，以及经典玩法中被抽掉的暗牌。
- 电脑玩家同样看不到你的牌，只会随机抽一个位置。
''';

const String _gofishRules = '''
# 钓鱼
经典的问牌凑书游戏，2～6 人，使用一副 52 张扑克牌。目标是凑齐四张同点数的牌，称为一“书”。

# 发牌
- 2～3 人每人发 7 张，4～6 人每人发 5 张，剩下的牌背面朝上作为“池塘”。
- 发牌后手里如果已经有四张同点，立即作为一书放下。

# 回合
- 轮到你时，选择一名还有手牌的玩家，并向他要一个点数。你要的点数必须是自己手里至少有一张的。
- 如果对方有这个点数，必须把这个点数的牌全部给你，然后你可以继续再要一次。
- 如果对方一张都没有，他会说“去钓鱼”：你从池塘摸一张牌。如果摸到的正好是你刚才要的点数，你还可以再来一次；否则轮到下家。
- 池塘已空时被拒绝，直接轮到下家。
- 任何时候凑齐四张同点数，自动放下成为一书。

# 手牌用完
- 轮到你时手里没有牌，先从池塘摸一张再问；如果池塘也空了，你就出局等待，不再行动。

# 结束与胜负
- 13 书全部完成时游戏结束，书最多的玩家获胜，书数相同者名次并列。

# 公开信息
- 所有的问牌和给牌都是公开的，桌面会显示问牌记录，例如“小明 向 阿猫 要 7：给了 2 张”或“去钓鱼”。
- 钓鱼摸到的牌只有自己知道（除非钓到了所要的点数，此时会公告“钓到了”）。
- 记住谁要过什么点数是取胜关键：别人向你要过的点数，说明他手里有！
- 电脑玩家只利用公开信息记牌：简单难度随机乱问；普通难度只记得最近几轮；困难难度会记住全部公开的问牌和给牌。
''';

const String _sevensRules = '''
# 牌七（接龙）
经典的出牌接龙游戏，3～6 人，使用一副 52 张扑克牌，全部发完（人数除不尽时有人多一张）。

# 出牌
- 持有红桃7（♥7）的玩家先出，第一手必须打出红桃7。
- 桌面上每种花色排成一行，从 A 到 K。某花色的 7 打出后这一行就开始了。
- 之后轮流出牌，每次出一张：可以出任意花色的 7 开新的一行，或者在已开始的行上紧挨着往下接（6、5、4…A）或往上接（8、9、10…K）。
- A 是最小的牌，只能接在 2 的下面；K 只能接在 Q 的上面。

# 不能出牌时（扣牌玩法，默认）
- 只要你有能接的牌，就必须出，不能扣牌，也不能过。
- 手里没有任何能接的牌时，必须从手里选一张牌背面朝下“扣”在自己面前。
- 被扣掉的牌不再出现，可能会把某一行堵死，让后面的牌也接不上——善用扣牌卡住别人！
- 所有人都出完或扣完手牌后游戏结束，按扣牌的点数计罚分：A=1，2～10 按面值，J=11，Q=12，K=13。
- 罚分最少的玩家获胜，罚分相同名次并列。扣下的牌只有自己能看到，结束时公开。

# 过牌玩法（选项）
- 没有能接的牌时直接说“过”，不扣牌；有牌能出时不能过。
- 第一个出完手牌的玩家获胜，其他玩家按剩余手牌点数从少到多排名。

# 策略提示
- 手里连成一串的牌可以早点出，后面能自己接。
- 卡住别人的关键牌（例如别人都在等的 6 或 8）可以晚点再出。
- 扣牌时尽量扣点数小的牌，但如果一张牌后面跟着你自己的一串牌，扣掉它也就扣掉了整串的机会。
''';

