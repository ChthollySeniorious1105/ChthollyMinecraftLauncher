const holdemRules = '''# 概述
- 无限注德州扑克，2~9 人。每人两张底牌，配合五张公共牌，任选五张组成最大的牌型。赢光对手筹码或比赛结束时筹码最多者获胜。
- 牌型从大到小：皇家同花顺、同花顺、四条、葫芦、同花、顺子、三条、两对、一对、高牌。A 可作 A-2-3-4-5 最小顺子。花色不分大小，完全相同则平分底池。

# 一手牌的流程
- 庄家按钮每手顺时针移动。按钮左侧依次下小盲、大盲；两人对局时庄家下小盲并在翻牌前先行动。
- 翻牌前、翻牌（3 张）、转牌（1 张）、河牌（1 张）共四轮下注，每发公共牌前烧一张牌。
- 可选择：弃牌、过牌（无人下注时）、跟注、加注、全下。最小加注额 = 本轮上一次完整加注的增量（至少一个大盲）。
- 不足一次完整加注的全下不会重新开放加注：已经行动过的玩家只能跟注或弃牌。
- 只剩一人未弃牌时他直接赢得底池，未被跟注的多余筹码退回。
- 摊牌时所有未弃牌玩家自动亮牌。全下产生边池，每个底池只在有资格的玩家中比牌；平分时零头给按钮左侧最近的赢家。

# 选项
- 初始筹码：1000 / 2000 / 5000。
- 盲注：10/20、25/50、50/100。
- 盲注递增：开启后每 10 手盲注翻倍。
- 结束条件：“淘汰至一人”打到只剩一人有筹码（最多 300 手，到达上限按筹码排名）；“固定30手”打满 30 手后按筹码排名。

# 名次与认输
- 筹码输光即出局。最终名次：未出局者按筹码多少排名，出局者按出局先后排名（越晚出局越靠前），同一手出局或筹码相同者名次并列。
- 仅限两人对局：可以认输，对手直接获胜。
- 与常见规则的差异：没有前注、没有自选亮牌/盖牌，摊牌一律亮牌；不支持悔棋。
''';

const blackjackRules = '''# 概述
- 1~7 名玩家各自与电脑庄家比牌，玩家之间互不影响。点数最接近 21 且不爆牌者胜。
- 牌点：2~10 按面值，J/Q/K 为 10，A 为 1 或 11。含一张按 11 计算的 A 称为“软”点数。
- 使用 6 副牌的牌靴，剩余不足四分之一时在下一局开始前重新洗牌。每人初始 1000 筹码。

# 一局的流程
- 下注：每人下注（最少 10，不能超过自己的筹码），全部下注后发牌：玩家两张明牌，庄家一明一暗。
- 保险：庄家明牌为 A 时，每位玩家可花一半注额买保险；庄家是黑杰克则保险赔 2:1。
- 庄家明牌为 10 点或 A 时先偷看暗牌，若是黑杰克立即结算：玩家除同为黑杰克（平局）外全部输掉本注。
- 玩家按座位顺序行动：要牌、停牌、加倍（仅限前两张，注额翻倍并只再拿一张）、分牌（前两张点数相同，另下等额注，最多分成 4 手）。分牌后仍可加倍；分开的 A 各只拿一张牌；分牌后凑成的 21 点不算黑杰克。达到或超过 21 点自动结束。
- 庄家最后亮牌，16 点及以下必须要牌，17 点及以上停牌；“软17”选项决定庄家软 17 时是否继续要牌。若所有玩家都已爆牌或拿到黑杰克，庄家不再要牌。

# 结算
- 黑杰克（前两张 A+10 点）赔 3:2（零头舍去），普通胜利赔 1:1，平局退回注额，爆牌直接输。
- 筹码少于 10 视为破产出局，不再参与。

# 选项
- 庄家软17：停牌或要牌。
- 局数：10 局、20 局或“直到破产”（最多 50 局）。所有人破产时提前结束。

# 名次
- 比赛结束时按剩余筹码排名，筹码相同名次并列。
- 与常见赌场规则的差异：没有投降、没有额外的偶然奖金；不支持认输与悔棋。
''';

const paodekuaiRules = '''# 概述
- 三人跑得快，每人独立作战，先出完手牌者赢得本局，其余玩家按剩余张数付分。
- 牌的大小（不分花色）：3 < 4 < … < K < A < 2。

# 发牌
- 16 张模式：去掉大小王、三张 2（只留红桃 2）和黑桃 A，共 48 张，每人 16 张。
- 15 张模式：去掉大小王、三张 2（只留红桃 2）、三张 A（只留红桃 A）和黑桃 K，共 45 张，每人 15 张。
- 每局都由持有黑桃 3 的玩家先出，且第一手必须包含黑桃 3。

# 牌型
- 单张、对子、连对（两对及以上相连的对子，如 5566）、顺子（5 张及以上相连，最大到 A，2 不能进顺子）。
- 三带二：三张相同加任意两张；飞机：两组及以上相连的三张（最大到 A），每组带两张。
- 最后一手出完时可以三带一、三张不带或飞机少带。
- 炸弹：四张相同，可以压任何非炸弹牌型，大炸弹压小炸弹。
- 跟牌必须同牌型、同长度且更大。其他两人都不要时，最后出牌者重新自由出牌。

# 特殊规则
- 报单：下家只剩一张牌时，你若出单张必须出手中最大的单张。
- 必须管（选项）：“有牌必管”时只要能管上就不能不要；“可以不管”时随时可以选择不要。

# 计分
- 赢家从每个输家处收取其剩余张数的分数；只剩一张的输家不用付分。
- 关门：整局一张牌都没出过的输家付双倍。
- 炸弹：每打出一个炸弹，另外两家各付 10 分给出炸弹者（本局立即计入）。
- 每局结束后亮出所有手牌，三人都点“继续”后开始下一局。

# 选项与名次
- 手牌数：16 张或 15 张；局数：5 局或 10 局。
- 打满局数后按总积分排名，积分相同名次并列。本游戏不支持认输与悔棋。
