/// 规则说明（GameDef.rules）
const String goRules = '''
# 目标
- 黑白双方轮流在棋盘交叉点上落子，争夺地盘。终局时按中国规则数子：己方活棋子数 + 围住的空点，加上贴目后多者获胜。
# 基本规则
- 黑先白后（让子局由白先行）。每次在空交叉点放一枚棋子，落下后不再移动。
- 气：棋子上下左右相邻的空点。相连的同色棋子共享气；一块棋没有气时被提掉。
- 禁止自杀：落子后己方棋块无气且不能提掉对方棋子，则不能下。
- 打劫：不能立即提回刚刚提掉自己一子的那一子，需先在别处落一手。本实现还禁止“全局同形重复”（超级劫），任何导致以前出现过的局面的落子都不允许。
- 可以随时“停一手”（pass）。双方连续停一手后进入数子阶段。
# 数子阶段
- 系统用蒙特卡洛估算自动标记死子（灰色标记）。双方可点击棋块切换其死活标记，任何修改都会取消双方的确认。
- 双方都点“确认”后结算；若对死活有异议可选择“继续对局”，由对方先下。
- 计分：黑方子+地 与 白方子+地+贴目 比较，差值即胜负子数；恰好相等为和棋（仅整数贴目可能出现）。
# 选项
- 棋盘：19 路（标准）/ 13 路 / 9 路（快棋、入门）。
- 贴目：7.5（中国规则常用）/ 6.5（日韩常用，本实现仍按数子法计算）/ 0.5（几乎不贴）。
- 让子：2~9 子，按标准星位放置黑子，随后白先。
# 结束方式
- 数子结算、认输（对方获胜）、双方同意和棋。
- 支持悔棋：经对方同意后撤回最近的着手。
# 与常见规则的差异
- 死活由双方在数子阶段手动确认，不做复杂的判定；电脑会直接确认系统估算的结果。
''';

const String chessRules = '''
# 目标
- 将死对方的王。白方先行，开局随机分配执白方。
# 棋子走法
- 王：向任意方向走一格；不能走到被攻击的格子。
- 后：横、竖、斜任意格数。车：横竖任意格数。象：斜线任意格数。
- 马：走“日”字（L 形），可以越过其他棋子。
- 兵：向前走一格，初始位置可走两格；斜前方一格吃子。
# 特殊走法
- 王车易位：王和车都未移动过、中间无子、王不在被将军状态且经过与到达的格子不被攻击时，王向车方向走两格，车越过王放在旁边。
- 吃过路兵：对方兵从初始位置一步走两格、停在己方兵旁边时，下一步可以像它只走一格那样斜吃它。
- 升变：兵走到底线必须升变为后、车、象或马（默认后）。
# 将军与胜负
- 被将军时必须应将；无合法着法且被将军即为将杀，走出将杀的一方获胜。
- 逼和：轮到走棋的一方无合法着法但未被将军，和棋。
# 自动和棋
- 同一局面第三次出现（三次重复）。
- 50 回合规则：连续 50 个回合（100 步）既没有吃子也没有兵的移动。
- 子力不足以将杀（如王对王、王象对王等）。
- 本实现为防止对局无限进行，总步数达到 300 步时判和。
# 认输与求和
- 可随时认输，对方获胜。可以向对方提议和棋，对方同意则和棋；对方走棋视为拒绝。
- 支持悔棋：经对方同意后撤回最近的着手。
''';

const String xiangqiRules = '''
# 目标
- 将死或困毙对方的将（帅）。红方先行，开局随机分配执红方。
# 棋盘
- 9 路 × 10 线，中间为“楚河汉界”，双方各有一个 3×3 的九宫。
# 棋子走法
- 帅/将：在九宫内横竖走一格。双方将帅不能在同一直线上直接照面（中间无子）。
- 仕/士：在九宫内斜走一格。
- 相/象：走“田”字对角，不能过河；田字中心有子时不能走（塞象眼）。
- 马：走“日”字；紧邻马的直线方向有子时不能向该方向跳（蹩马腿）。
- 车：横竖任意格数，不能越子。
- 炮：不吃子时同车；吃子时必须隔一个棋子（炮架）跳吃。
- 兵/卒：未过河只能前进一格；过河后可前进或左右平移一格，不能后退。
# 胜负
- 被将军必须应将，不能走出让己方将帅被攻击或照面的棋。
- 一方无合法着法即输：被将军时为“绝杀”，未被将军时为“困毙”（象棋中困毙同样判负）。
# 和棋
- 同一局面第三次出现时判和（本实现简化了长将、长捉的判负规则，统一按重复判和）。
- 双方都没有能过河进攻的子力（车、马、炮、兵）时判和。
- 总步数达到 300 步判和。
# 认输与求和
- 可随时认输，对方获胜；可以提议和棋，对方同意则和棋，对方走棋视为拒绝。
- 支持悔棋：经对方同意后撤回最近的着手。
''';
