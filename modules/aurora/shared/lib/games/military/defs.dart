const junqiRules = '''
# 棋子
- 每方 25 枚：司令、军长各 1，师长、旅长、团长、营长各 2，连长、排长、工兵各 3，地雷 3，炸弹 2，军旗 1。
- 大小：司令 > 军长 > 师长 > 旅长 > 团长 > 营长 > 连长 > 排长 > 工兵。大吃小，同级同归于尽。
- 炸弹与任何棋子相碰双方同时消失；地雷只有工兵能排除，其他棋子撞雷阵亡（地雷留下）；炸弹碰地雷同归于尽。
- 军旗、地雷不能移动；任何棋子都可以夺取军旗。
# 棋盘与走法
- 公路线（细线）每步只走一格；铁路线（粗线）上可直行任意格，途中不能越过棋子；工兵在铁路上可以拐弯。
- 行营（圆圈）里的棋子不能被攻击；大本营里的棋子不能再移动。
- 己方棋子不能互相吃，四国中队友的棋子也不能攻击。
# 两国军棋（2 人）
- 布阵阶段：系统先随机摆好，点击两枚己方棋子可交换位置，也可以“随机”重排，完成后点“准备”。
- 布阵限制：军旗必须在大本营；地雷只能在最后两排；炸弹不能在第一排。
- 对手的棋子始终是暗的，只能从碰子结果推断；由裁判（系统）判定胜负。司令阵亡后，该方的军旗会亮出。
- 夺取对方军旗，或对方无子可走，即获胜。
# 四国军棋（4 人）
- 座位 1、3 与座位 2、4 分别组队（对家为队友），队友之间互相可见棋子。
- 按座位顺序轮流行棋；某人军旗被夺、无棋可走或认输即出局，其棋子全部撤出棋盘。
- 一方两人都出局时另一队获胜，胜队两人都算第一名。
# 翻翻棋（2 人）
- 50 枚棋子全部背面朝上随机摆在非行营位置。每回合可以翻开一枚棋子或走动一枚已翻开的己方棋子。
- 第一个翻棋的玩家执所翻棋子的颜色，另一方执另一色。
- 翻开的棋子双方都可见；背面朝上的棋子不能被攻击。大本营里的棋子也可以移动。
- 某一色的地雷全部消失后，才能夺取该色的军旗。夺旗或对方无棋可走即获胜。
# 其他
- 认输：两国/翻翻棋直接判对方获胜；四国中认输者出局，队友继续，直到一队全部出局。
- 求和：所有真人玩家同意后和棋。总步数达到 1000 步也判和棋。
- 本游戏含隐藏信息，不支持悔棋。电脑只根据自己能看到的信息和公开的碰子结果推理。
''';

const animalChessRules = '''
# 棋盘
- 7 列 × 9 行。红方（先手）在下方，蓝方在上方。
- 中间有两块河（各 2×3 格）；每方底线中央是兽穴，兽穴左右和前方各有一个陷阱。
# 棋子
- 每方 8 只动物，从大到小：象 8、狮 7、虎 6、豹 5、狼 4、狗 3、猫 2、鼠 1。
- 每步把一只动物横或竖走一格，不能走进自己的兽穴。
- 大吃小、同级可以互吃；例外：鼠可以吃象，象不能吃鼠。
# 特殊规则
- 只有鼠能下河游泳。鼠在河里不能吃岸上的动物，岸上的动物也不能吃河里的鼠（河里的鼠可以吃河里的鼠）。
- 狮、虎可以横向或纵向跳过整条河，落到对岸；若跳跃路线上的河里有鼠（任何一方）则不能跳。跳到的位置可以吃子。
- 动物走进对方的陷阱后战斗力变为 0，对方任何动物都能吃掉它；回到己方区域后恢复。
# 胜负
- 任意一只动物走进对方兽穴立即获胜。
- 对方无子可走（全部被吃或被困）也获胜。
- 总步数达到 300 步判和棋。
- 可以认输（对方获胜），双方同意可以和棋，支持悔棋。
# 电脑难度
- 简单：经常随便走；普通：看一步应对；困难：限时的多层搜索。
''';
