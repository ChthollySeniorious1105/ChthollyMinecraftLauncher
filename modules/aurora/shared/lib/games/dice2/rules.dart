const String shiDianBanRules = '''
# 概述
- 十点半是一种比点数的扑克游戏：一名庄家对其余所有闲家，每位闲家分别与庄家比牌。目标是让手牌点数尽量接近 10.5 点，但不能超过（超过即“爆牌”）。
- 使用一副 52 张牌（无大小王），每局重新洗牌。每人起始筹码 1000。

# 点数
- A 算 1 点，2~10 按牌面点数，J、Q、K 各算半点（0.5）。

# 一局流程
- 定庄：选项“轮庄”时庄家按座位轮流；“抢庄”时所有人同时选择抢或不抢，从抢庄者中随机选出庄家（都不抢则从所有人中随机）。
- 发牌：每人发一张暗牌（只有自己能看到）。
- 下注：每位闲家从 10 / 20 / 50 / 100 中选择下注额，庄家不下注。
- 要牌：从庄家下家开始，闲家依次选择“要牌”（加一张明牌）或“停牌”。爆牌立即亮牌并结束；凑满 10.5 点或手中达到 5 张牌时自动停牌。
- 庄家最后要牌；如果所有闲家都已爆牌，庄家不用再要牌直接结算。

# 牌型（由大到小）
- 人五小：5 张牌全是 J/Q/K（共 2.5 点）。
- 天王：5 张牌且正好 10.5 点。
- 五小：5 张牌且不超过 10.5 点。
- 十点半：少于 5 张且正好 10.5 点。
- 平牌：不超过 10.5 点的其他牌，按点数比大小。
- 爆牌：超过 10.5 点。

# 结算
- 闲家爆牌：无论庄家如何，闲家输掉下注额（×1）。
- 庄家爆牌（闲家未爆）：庄家按闲家的牌型赔率赔付。
- 双方都没爆：牌型大者赢，按赢家牌型的赔率结算；同为平牌比点数，点数大者赢（平牌赔 ×1）。
- 牌型与点数完全相同时算庄家赢。
- 赔率选项：标准（十点半 ×2、五小 ×3、天王 ×4、人五小 ×5）；高倍（×3 / ×5 / ×6 / ×8）；平赔（任何牌型一律 ×1）。

# 胜负
- 打满选定的局数（6 / 10 / 16 局）后结束，按筹码多少排名，筹码最多者获胜（筹码相同名次并列）。
- 筹码允许为负数，不会中途淘汰。
''';

const String dicePokerRules = '''
# 概述
- 骰子扑克：每人轮流用 5 颗骰子组成类似扑克的牌型，每局牌型最大的玩家得 1 分，打满局数后得分最多者获胜。

# 一局流程
- 每局从不同的玩家开始，按座位顺序轮流进行，每人一回合。
- 回合内最多掷 3 次：第一次必须掷全部 5 颗；之后可以点选任意骰子“保留”，只重掷其余骰子（不能 5 颗全保留，那就直接停手）。
- 至少掷一次后可以随时“停手”，以当前 5 颗骰子作为本局成绩；掷满 3 次自动停手。
- 所有人都完成后比较牌型，最大者得 1 分；若并列最大，并列者各得 1 分。

# 牌型（由大到小）
- 五条：5 颗相同。
- 四条：4 颗相同。
- 葫芦：3 颗相同 + 2 颗相同。
- 大顺：2-3-4-5-6。
- 小顺：1-2-3-4-5。
- 三条：3 颗相同。
- 两对。
- 一对。
- 散牌：以上都不是。
- 同牌型比较：先比组成牌型的主要点数（例如三条比三条的点数，两对先比大对再比小对），再依次比剩余骰子点数，全部相同为平局。

# 胜负
- 局数选项：5 局或 10 局。打满后得分最多者获胜，得分相同名次并列。
- 认输：认输的玩家立即退出，之后的局不再轮到他，最终排名在所有未认输玩家之后；只剩一人时游戏直接结束。
''';

const String pigRules = '''
# 概述
- 猪骰（Pig）是经典的“见好就收”骰子游戏：轮到你时可以不停地掷骰累积本回合分数，但一旦掷出 1，本回合分数全部作废。先达到目标分的玩家获胜。

# 回合流程
- 随机决定先手，之后按座位轮流。
- 轮到你时至少掷一次。每次掷骰后可以选择：
- 继续掷：点数加入本回合累计分。
- 存分（停手）：把本回合累计分加入总分，轮到下一位。
- 掷出 1：本回合累计分作废，直接轮到下一位（总分不受影响）。

# 双骰猪（选项）
- 每次掷两颗骰子，两颗点数之和计入本回合累计分。
- 只要有一颗是 1：本回合累计分作废，轮到下一位。
- 两颗都是 1（蛇眼）：不仅本回合作废，已经存下的总分也全部清零！

# 胜负
- 目标分选项：50 分或 100 分。
- 总分加上本回合累计分一达到目标分立即获胜，不需要再存分，游戏结束。
- 排名：获胜者第 1，其余玩家按总分排名（同分并列）。
- 认输：认输的玩家出局并排在最后，其他人继续；只剩一人时他直接获胜。
''';

const String farkleRules = '''
# 概述
- 快乐骰（Farkle）：用 6 颗骰子掷出计分组合，一回合内可以反复掷骰累积分数，但如果某次掷出的骰子里没有任何可计分的组合（Farkle），本回合分数全部作废。

# 回合流程
- 掷出所有可用骰子后，必须至少留下一组计分骰（所选骰子必须全部计分）。
- 留下后可以选择“继续掷”（用剩下的骰子再掷）或“存分”（把本回合累计分加入总分，回合结束）。
- 满堂骰：6 颗骰子全部被留作计分骰时，可以重新拿起全部 6 颗继续掷，累计分保留。
- 掷出后无任何计分组合即为 Farkle，本回合累计分清零，轮到下一位。

# 计分
- 单个 1 = 100 分，单个 5 = 50 分。
- 三条：点数 × 100（三个 1 = 1000）。
- 四条 = 三条分 × 2，五条 = × 4，六条 = × 8。
- 顺子 1-2-3-4-5-6 = 1500 分（必须一次掷出 6 颗时）。
- 三对 = 750 分（四条 + 一对也算三对，取两种算法中较高者）。
- 同一次选择中的多个组合分数相加，例如 1-1-1-5 = 1050。只有同一次掷出的骰子才能组成组合。

# 结束与胜负
- 目标分选项：5000 或 10000 分。
- 某位玩家存分后总分达到目标分，其他每位玩家还各有最后一回合。
- 最后一轮结束后总分最高者获胜，同分并列。排名按总分。
- 认输：认输的玩家出局并排在最后，其余人继续；只剩一人时他直接获胜。
''';

const String chuiNiuRules = '''
# 概述
- 吹牛骰（大话骰）：每人 5 颗骰子扣在骰盅下，只能看到自己的骰子。玩家轮流“叫”场上一共至少有几个某点数，下家要么叫得更大，要么“开”来验证。

# 叫骰
- 叫法为“几个几”，例如“5 个 4”表示全场所有骰子中至少有 5 个 4。
- 1 点是万能的，可以当作任何点数计算（叫“斋”或叫 1 点时除外）。
- 斋：宣布 1 不再万能（只数真正的该点数）。叫 1 点本身永远算斋。
- 开局最少叫数：飞（普通叫法）至少叫“存活人数 + 1”个，斋至少叫“存活人数”个。
- 加叫规则：数量更多；或数量相同但点数更大（点数大小：2 < 3 < 4 < 5 < 6 < 1）。
- 飞改斋：数量不能少于上家；斋改飞：数量至少翻倍。

# 开与劈
- 开：不相信上家的叫数，所有人亮骰。若场上实际个数 ≥ 叫数，开的人输；否则叫的人输。输家扣 1 条命。
- 劈（选项）：比开更狠，赌注 ×2。被劈的人可以选择“接受”（按 ×2 开）或“反劈”（赌注再翻倍到 ×4 后开）。
- 输家从下一轮开始先叫。

# 胜负
- 生命选项：3 条命或 5 条命。命数归零即出局，他的骰子不再计入场上。
- 最后存活的玩家获胜；其余按出局先后排名，越晚出局名次越好。
- 认输：认输即出局，与命数耗尽一样按出局先后排名；当前一轮作废，由下一位存活玩家重新摇骰开叫。
''';
