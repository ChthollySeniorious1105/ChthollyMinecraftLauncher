/// 规则说明（GameDef.rules）。
const String onenightRules = '''
# 游戏概述
一夜终极狼人是只有一个夜晚的快节奏狼人游戏，3~10 人。身份牌比人数多 3 张，多出的 3 张放在中间。夜里部分角色会查看或交换身份牌，所以天亮后你的身份不一定还是开局那张。

# 角色
- 狼人：夜里互相确认；如果只有一名狼人（独狼），可以查看中间一张牌。
- 爪牙：知道谁是狼人，狼人不知道他。爪牙属于狼人阵营。
- 预言家：查看一名玩家的牌，或中间的两张牌。
- 强盗：与一名玩家交换牌，并查看自己的新身份。
- 捣蛋鬼：交换另外两名玩家的牌（自己不看）。
- 酒鬼：把自己的牌与中间一张交换，不知道新身份。
- 失眠者：天亮前查看自己最终的身份。
- 猎人：如果被投出，他投票的对象也一起出局。
- 皮匠：想被投出；皮匠出局则皮匠获胜。
- 村民：没有技能。
- 夜晚结算顺序：狼人 → 爪牙 → 预言家 → 强盗 → 捣蛋鬼 → 酒鬼 → 失眠者。

# 流程
- 夜晚：每人查看身份并完成夜间行动（没有行动的角色直接确认）。夜里所有人都不能说话。
- 白天：自由讨论（3/5/8 分钟），可以在聊天中发言；所有人都点“提前投票”即可提前结束讨论。
- 投票：所有人同时投票给另一名玩家，得票最多（且至少 2 票）的玩家出局，平票则一起出局；所有人都只得 1 票时无人出局。

# 胜负（按最终身份判定）
- 至少一名狼人出局：好人阵营获胜。
- 场上有狼人但没有狼人出局：狼人阵营获胜（若皮匠出局则狼人也不能获胜）。
- 场上没有狼人：无人出局（或只投出爪牙）好人获胜；否则好人失败，爪牙获胜。
- 皮匠出局：皮匠获胜。
- 获胜者第 1 名，其余第 2 名。

# 选项
- 角色配置：标准 / 新手 / 混乱，按人数取前 N+3 张。
- AI 电脑：开启后电脑玩家会在白天由大模型根据自己开局的身份与夜里得知的信息发一两句言（狼人会伪装），并由大模型推理投票；失败时改用普通电脑。
- 电脑难度：简单的电脑经常随便投票。
''';

const String resistanceRules = '''
# 游戏概述
抵抗组织是一款阵营推理游戏，5~10 人。大部分玩家是抵抗组织成员，少数是潜伏的间谍（5~6 人 2 名，7~9 人 3 名，10 人 4 名）。间谍彼此认识，抵抗组织成员不知道谁是间谍。

# 流程
- 组队：队长按本次任务人数提名队员（人数随玩家数和任务轮次变化）。
- 投票：所有人公开投赞成或反对，超过半数赞成才能出发；否则队长顺延。连续 5 次组队被否决，间谍直接获胜。
- 任务：队员秘密出“成功”或“失败”，抵抗组织成员只能出成功。有 1 张失败任务就失败（7 人以上第 4 次任务需要 2 张失败）。
- 共 5 次任务，先拿到 3 次成功（抵抗组织）或 3 次失败（间谍）的一方获胜。

# 计划卡（可选）
- 每次任务开始时队长抽一张计划卡（三种各 3 张，用完重洗）：
- 窃听：队长把此卡交给一名其他玩家，该玩家查看自己左右相邻的一名玩家的阵营。
- 坦白：队长把此卡交给一名其他玩家，该玩家向任意一名玩家公开自己的阵营。
- 建立信任：队长必须向一名其他玩家公开自己的阵营。
- 得知的阵营信息只有相关玩家自己知道。

# 胜负
- 3 次任务成功：抵抗组织获胜；3 次任务失败或连续 5 次否决：间谍获胜。
- 获胜阵营全员第 1 名，失败阵营全员第 2 名。

# 电脑
- 抵抗组织电脑只根据公开的任务结果和自己得到的计划卡信息推理；间谍电脑知道同伴。
- 本游戏没有文字发言环节，电脑不使用大模型。简单的电脑经常随意投票、乱选队员；困难的电脑更依赖任务记录。
''';

const String spyfallRules = '''
# 游戏概述
谁是间谍（Spyfall）是一款问答推理游戏，3~10 人。每轮随机抽一个地点，除间谍外每人都知道地点，并得到一个该地点的身份（例如“医院·护士”）；间谍只知道自己是间谍。

# 流程
- 从随机一名玩家开始，提问者选择另一名玩家提一个问题（不能反问刚刚问自己的人），被问者回答后成为下一个提问者。
- 平民要通过问答判断谁不知道地点；但问题和回答不能太直白，否则间谍会猜出地点。
- 间谍要装作知道地点，并从大家的问答中推断地点。

# 指认与猜地点
- 每人每轮可以发起一次指认：其他人（被指认者除外）表决，需要全票通过才成立。指认成立时翻开被指认者身份。
- 间谍可以随时亮明身份猜地点：猜对间谍获胜，猜错平民获胜。
- 时间到时，所有人投票指认间谍；得票过半且唯一最多的玩家被票出。

# 计分
- 平民获胜：每名平民 +1 分，发起成功指认者 +2 分（替代 1 分）。
- 间谍猜中地点或平民冤枉好人：间谍 +4 分；时间到间谍成功潜伏：间谍 +2 分。
- 多轮结束后按总分排名，同分并列。

# 选项
- 每轮时间 6/8/10 分钟、轮数 1/3/5 轮。
- AI 电脑：开启后电脑玩家由大模型根据地点和身份提问、回答（平民不会直接说出地点），电脑间谍会根据问答推断并猜出地点（只能从地点列表中选择），失败时改用普通电脑。
- 电脑难度：简单的电脑更爱乱指认；困难的电脑会指认回答最含糊的人。
''';
