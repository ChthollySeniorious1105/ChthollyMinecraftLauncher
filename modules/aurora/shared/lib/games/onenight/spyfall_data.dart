/// Answer → the pack it belongs to (names are unique across packs).
final Map<String, SpyfallPack> spyfallPackOf = {
  for (final p in spyfallPacks)
    for (final k in p.items.keys) k: p,
};

/// Items for a pack id; 'mix' merges all packs.
Map<String, List<String>> spyfallItems(String packId) {
  if (packId == 'mix') return {for (final p in spyfallPacks) ...p.items};
  return spyfallPacks.firstWhere((p) => p.id == packId, orElse: () => spyfallPacks.first).items;
}

/// What the answer is called for a pack id (mixed: 词条).
