- 炸弹：4 张及以上同点，可管一切非炸弹；炸弹之间张数多者大，同张数比点数。
- 王炸：一副牌时为大小王两张，两副牌时为全部四张王，最大。

# 出牌
- 首家可出任意牌型；其余玩家依次选择管上或“不要”。除最后出牌者外其他在场玩家都不要时，他赢得这一轮并重新领出。
