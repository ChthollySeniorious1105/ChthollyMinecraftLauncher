const baccaratRules = '''
# 概要
- 1~8 位玩家各自与电脑庄家对赌，每人初始 1000 筹码。玩家之间不互相输赢，最终按剩余筹码排名（相同并列）。
- 选项“局数”：10 / 20 / 40 局。筹码不足 10 的玩家不能再下注；所有人都破产时提前结束。

# 牌靴
- 八副牌（不含王）洗匀。翻开第一张，按其点数（10/J/Q/K 算 10）再烧掉相应张数。
- 在牌靴末端 60~90 张处放切牌卡，发到切牌卡后，本局结束换新牌靴。

# 下注
- 每局所有玩家同时下注（也可以不下），别人的金额在开牌时公开。
- 可押：庄、闲、和，选项“对子”开放时还可以押闲对、庄对。每个区域至少 10，总额不能超过自己的筹码。

# 开牌与补牌
- 闲、庄各发两张。A 为 1 点，2~9 按面值，10/J/Q/K 为 0，点数取总和的个位。
- 任一方两张为 8 或 9（例牌）则都不补牌。
- 闲 0~5 补一张，6~7 不补。
- 闲不补时，庄 0~5 补、6~7 不补；闲补牌时庄按第三张牌决定：庄 0~2 必补；3 点除闲第三张为 8 外都补；4 点在闲第三张为 2~7 时补；5 点在 4~7 时补；6 点在 6~7 时补；7 点不补。
- 点数接近 9 的一方胜，相同为和。

# 赔率
- 庄赢 1 赔 0.95（抽 5% 佣金，结算时按整数向下取整）；闲赢 1 赔 1；和 1 赔 8，开和时庄、闲的注退回。
- 闲对 / 庄对：该方前两张同点数（不论花色）时 1 赔 11。
- 与常见规则的差异：没有免佣百家乐、大小、超级六等玩法，庄家资金无限。
''';
