const gandengyanRules = '''
# 概要
- 2~6 人，一副 54 张牌（含大小王）。每局庄家 6 张、其余每人 5 张，剩下的牌作为摸牌堆。庄家先出。
- 选项“局数”：打 3 / 6 / 10 局，按累计分排名，分数最高者第一（同分并列）。

# 牌型
- 单张、对子、顺子（3 张及以上连续，最大到 A，2 不能进顺子）、连对（2 对及以上连续，最大到 A）。
- 炸弹：3 张及以上同点。两张王为王炸，最大。
- 大小王是百搭，可代替任意牌组成对子、顺子、连对、炸弹；单出一张王时按 2 计算（跟牌时可当作任意需要的单张）。
- 点数大小：3 < 4 < … < K < A < 2。

# 出牌
- 首家可出任意合法牌型，首家不能不要。
- 跟牌必须与桌面同牌型、同张数，并且恰好大一级（单张 5 只能用 6 管，顺子 3-4-5 只能用 4-5-6 管）。
- 2 可以管任意单张 / 对子（2 不能管 2）。
- 炸弹可管一切非炸弹；炸弹之间张数多的大，张数相同比点数；王炸最大。
- 轮到你也可以选择“不要”。一轮所有人都不要、又轮回到最后出牌的人时，他先从牌堆摸一张牌（牌堆空了就不摸），再重新领出。

# 结算
- 有人出完手牌即本局结束，他赢得其余每人“剩余张数 × 倍数”的分数。
- 本局每打出一个炸弹（含王炸），倍数翻一倍（最多 2^10）。
- 一张牌都没出过的玩家为“闷”，再翻一倍。
- 本局赢家成为下一局的庄家。

# 其他
- 两人对局可以认输，对手直接获胜。
- 与常见玩法的差异：没有“一次出完翻倍”“春天”等附加倍数；三张同点直接算炸弹。
''';

const wushikRules = '''
# 概要
- 一副 54 张牌（含大小王），全部发完。选项“模式”：四人对家组队（座位 1、3 一队，2、4 一队），或 3~5 人各自为战。
- 选项“局数”：1 / 4 / 8 局。首局随机先出，之后由上一局的头游先出。

# 牌型
- 单张、对子、三张（不带牌）、顺子（5 张及以上，3 到 A，2 和王不能进）、连对（2 对及以上）、飞机（2 组及以上连续三张，不带翅膀）。
- 跟牌必须同牌型、同张数且更大；点数 3 < … < A < 2 < 小王 < 大王。
- 炸弹可管一切非炸弹，大小顺序：杂色 510K < 纯色 510K（♦ < ♣ < ♥ < ♠）< 4 张炸弹 < 5 张炸弹 < … （张数多者大，同张数比点数）< 王炸（大小王）。
- 510K 即一张 5、一张 10、一张 K；同花色为纯 510K。杂 510K 之间不能互管。

# 分数
- 5 = 5 分，10 和 K = 10 分，全副共 100 分。
- 一轮其他在场玩家都“不要”后，最后出牌者赢得这一墩，墩里的分归他。
- 出完牌的人离场；如果赢墩者已经出完，组队时由对家接风先出，否则由下一位在场玩家先出。
- 本局结束时，所有人手里剩下的分都归头游（第一个出完的人）。

# 本局结束
- 各自为战：只剩一人有牌时结束，每人加上自己本局拿到的分。
- 组队：某一队两人都出完时结束，两队各自合计本局得分，队员两人都加上本队分数。

# 胜负
- 按累计分排名。组队时累计分高的一队两人并列第一，另一队并列第二；平分则全部并列第一。
- 与常见玩法的差异：不计“头游/末游”额外奖罚，没有三带二、四带二，王只能单出、成对或组成王炸。
''';

