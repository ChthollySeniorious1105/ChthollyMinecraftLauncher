const hanabiRules = '''
# 游戏概述
- 2~5 人合作游戏：所有人同属一队，共同得分，没有输赢之分（结算时所有玩家并列第一，分数代表本局演出质量）。
- 目标是按 1→5 的顺序把每种颜色的烟花打出来，满分 25 分（开启彩色烟花为 30 分）。

# 牌组与手牌
- 每种颜色 10 张：1 有 3 张，2、3、4 各 2 张，5 只有 1 张。基础为红黄绿蓝白 5 色，共 50 张。
- 2~3 人每人 5 张手牌，4~5 人每人 4 张。
- 你看不到自己的手牌，却能看到其他所有人的手牌。新摸的牌放在最左边（最新），最右边未被提示过的牌称为“弃牌位”。
- 开局有 8 个提示标记、3 次失误机会（引信），随机决定先手。

# 回合行动（三选一）
- 提示：消耗 1 个提示标记，选择另一名玩家，告诉他手中“所有”某种颜色的牌或“所有”某个数字的牌（必须至少指出一张）。被提示的信息会一直标注在牌上。没有提示标记时不能提示。
- 弃牌：弃掉自己的一张牌并恢复 1 个提示标记，然后摸一张。提示标记已满 8 个时不能弃牌。
- 打出：打出自己的一张牌。若它正好是该颜色下一个需要的数字，就放到对应烟花上；否则失败，该牌进入弃牌堆并用掉 1 次引信。之后摸一张。
- 成功打出某色的 5 时，若提示标记不满 8 个，额外恢复 1 个。

# 游戏结束
- 引信用完（第 3 次失误）：烟花秀失败，本局得 0 分。
- 所有颜色都打到 5：完美演出，立即结束。
- 牌堆摸完后，每人（包括摸到最后一张的人）再进行最后一个回合后结束。
- 得分 = 各色烟花最高数字之和。

# 选项说明
- 彩色烟花（第 6 种颜色）：加入彩色，共 60 张，满分 30。本实现中彩色是普通的第 6 种颜色（每色 10 张、数量分布同上），提示颜色时彩色只对“彩色”提示响应，不是万能色。

# 电脑玩家
- 电脑遵循常见的 H-group 式约定：新提示的焦点牌若可能可打则视为“打出提示”，否则视为“保留提示”；优先保护弃牌位上的关键牌（唯一剩余的牌、5）。电脑绝不查看自己的手牌，只根据提示和别人手中可见的牌推理。

# 其他
- 合作游戏不支持认输；也不支持悔棋（手牌隐藏）。
''';
