# 游戏概述
- 2~5 人。使用卡卡颂基础版 72 块地形板块（含起始板块），轮流抽取并拼接板块，派出跟随者占领城市、道路、修道院和草地来得分。游戏结束时总分最高者获胜，同分并列。
- 每人 7 个跟随者。起始板块放在桌面中央，随机决定先手。

# 回合流程
- 抽牌：系统从牌堆顶翻开一块板块（只有当前玩家的这一块是公开的，牌堆顺序对所有人隐藏）。若这块板块在任何位置、任何方向都放不下，自动弃置并重抽。
- 放置板块：可旋转 0/90/180/270 度，必须与至少一块已有板块相邻，且所有相邻的边都要吻合（城市对城市、道路对道路、草地对草地）。
- 派出跟随者（可选）：只能放在刚放下的这块板块上的某个区域（城市 / 道路 / 修道院 / 草地），并且该区域连通后的整片地形上不能已有任何跟随者（包括自己的）。也可以选择不放。
- 计分：放置后立即检查因这块板块而完成的城市、道路、修道院，结算分数并把上面的跟随者退回手中。

# 完成地形计分
- 道路：两端都封闭（路口、城市、修道院或环路）即完成，每块板块 1 分。
- 城市：城墙完全围合即完成，每块板块 2 分，每个盾徽额外 2 分。
- 修道院：自身及周围 8 格全部放满即完成，得 9 分。
- 同一片地形上若有多名玩家的跟随者（通过后来拼接合并而来），跟随者数量最多的玩家得全部分数；数量并列则并列者都得全分，其余人不得分。

# 游戏结束与终局计分
- 牌堆抽完（最后一块放置并结算后）游戏结束，进行终局计分：
- 未完成的道路：每块 1 分；未完成的城市：每块 1 分、每个盾徽 1 分；未完成的修道院：自身及周围已有板块每块 1 分。
- 草地（农夫）：每片草地由跟随者最多的玩家得分，该草地每邻接一座“已完成”的城市得 3 分。农夫一旦放下直到游戏结束都不会收回。
- 总分最高者获胜，同分并列名次。

# 认输
- 仅两人局可以认输：认输方判负，对手直接获胜。多人局不支持认输（可托管给电脑）。

# 选项说明
- 农夫（草地计分）：开启时可把跟随者放到草地上并在终局计分；关闭时草地不能放跟随者，也不计分（适合新手的简化规则）。

# 与常见规则的差异
- 不含任何扩展（河流、商人、旅店等）。无处可放的板块自动弃置重抽。
- 不支持悔棋（板块抽取带有隐藏信息）。
