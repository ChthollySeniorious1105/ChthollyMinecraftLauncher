/// 规则说明（GameDef.rules）
const String shogiRulesText = '''
# 概述
- 日本将棋，9×9 棋盘，双方各 20 枚棋子。先手执☗（下方），后手执☖（上方）。平手局由系统随机决定先后手。
- 目标：将死（诘）对方的玉将。

# 棋子走法
- 玉将：八方向各走一格。
- 飞车：直线任意格；升变为龙王，额外可斜走一格。
- 角行：斜线任意格；升变为龙马，额外可直走一格。
- 金将：前、左前、右前、左、右、后各一格（不能斜后退）。
- 银将：前方三格与斜后两格各一格。
- 桂马：只能向前跳“日”字的两个落点（前二格再左右一格），可越子，不能后退或横跳。
- 香车：只能向前直走任意格。
- 步兵：只能向前一格，吃子也只能向前。
- 升变后的银、桂、香、步都按金将的走法移动。

# 升变
- 敌阵为对方的三行。棋子移动的起点或终点在敌阵内时，可以选择升变（成）或不升变（不成）；金将和玉将不能升变。
- 若不升变就再也无法移动（步、香到底线，桂到最后两行），则必须升变。
- 被吃掉的升变棋子回到手中时恢复为原来的棋子。

# 打入（持驹）
- 吃掉的对方棋子归自己所有，放在驹台上。轮到自己时可以用一步把它“打”在任意空格上（代替走子），打入时总是未升变状态。
- 不能打在以后再也无法移动的位置（步、香不能打在最后一行，桂不能打在最后两行）。
- 二步：同一纵列上已有己方未升变的步兵时，不能再打入步兵。
- 打步诘：不能用打入步兵的方式直接将死对方（走步将死、打步将军不将死都可以）。

# 胜负与和棋
- 将死对方或对方无子可动即获胜；不能走出让自己的玉被将的棋（送将不合法，被将时必须应将）。
- 千日手：同一局面（含持驹、轮到谁走）出现第四次时判和；但若是一方一直连续将军造成的，则连续将军的一方判负。
- 持将棋：本实现简化为总手数达到 400 手判和（不做入玉点数计算）。
- 认输：任一方可随时认输，对方获胜。求和：双方同意后以和棋结束。

# 选项
- 让子：平手；让香（上手去掉左香）；让角；让飞；让二枚（去掉飞角）。让子局中上手执☖并先走，由系统随机决定谁是上手。
- 支持悔棋（棋局完全确定，可按操作记录重建）。电脑难度：简单常走随机步，普通为短时间搜索，困难搜索更深。
''';

const String jieqiRulesText = '''
# 概述
- 揭棋是中国象棋的暗子变体。棋盘、九宫、河界、将帅及各棋子的走法与中国象棋相同，红方先走（由系统随机决定谁执红）。
- 目标：将死（绝杀）对方的帅/将，或使对方无子可走（困毙）。

# 开局
- 帅和将放在原位且明置。其余每方 15 枚棋子（仕2、相2、马2、车2、炮2、兵5）被随机打乱，背面朝上摆在象棋的标准开局位置上。
- 暗子双方都看不到身份（包括自己的）。

# 暗子走法
- 暗子按照它所在“初始格”对应的兵种走第一步：例如在车位的暗子按车走，在炮位的按炮走，在兵位的按兵走（只能前进一步）。
- 仕位、相位上的暗子按仕、相的走法走，不能出九宫或过河。
- 暗子一旦走动就翻开，从此按真实身份行棋。暗子也可以吃子，吃子后同样翻开。
- 暗子只会在初始格，因此它的走法永远由初始位置决定。

# 明子走法
- 翻开后的棋子按真实身份行棋，与中国象棋相同：车直行、马走日（蹩马腿）、炮隔子吃、兵过河后可横走。
- 与象棋的差别：翻开后的仕、相不受九宫和河界限制，可以走到棋盘任何位置（仍按斜一格、田字并受塞象眼限制）。
- 帅将仍不能出九宫，且不能照面（飞将）。

# 吃子信息
- 被吃掉的暗子：默认只有吃子方知道它是什么（对方只看到被吃了一个暗子）；选项“被吃暗子：公开”时双方都能看到。对局结束后全部公开。

# 胜负与和棋
- 绝杀或困毙对方获胜；不能送将，被将军时必须应将。
- 同一局面出现三次判和；双方都只剩将帅判和；总步数达到 300 步判和。本实现不做长将、长捉判负的裁定。
- 认输：任一方可随时认输，对方获胜。求和：双方同意后以和棋结束。

# 其他
- 因暗子身份随机，本游戏不支持悔棋。
- 电脑只根据公开信息（以及自己吃到的暗子）思考，不会偷看暗子。难度：简单常走随机步，普通为短时间搜索，困难搜索更深。
''';
