const String wordleRules = '''
# Wordle 猜词
所有玩家同时猜同一个隐藏的英文单词（5 个字母），每人最多 6 次机会，比谁猜得又快又准。支持 1~8 人，一个人也可以单独练习。

# 怎么猜
- 每次输入一个 5 个字母的英文单词（必须是词库里的真实单词，约 8600 个），按回车或“提交”。不在词库中或长度不对的输入不算次数，会提示你重新输入。
- 提交后每个字母会变色：
- 绿色：这个字母在答案中，而且位置正确。
- 黄色：这个字母在答案中，但不在这个位置。
- 灰色：答案中没有这个字母（或者这个字母在答案中出现的次数已经被其他格子用完了）。
- 重复字母的规则与原版一致：先标出所有绿色，再从左到右分配黄色，每个答案字母最多对应一个猜测字母。例如答案 APPLE，猜 PAPAL：第 1 个 P 黄、第 1 个 A 黄、第 2 个 P 绿、第 2 个 A 灰、L 黄。
- 屏幕下方的键盘会按你已知的最好状态给每个字母上色，也可以直接用电脑键盘打字（字母、退格、回车）。

# 防抄袭
- 你只能看到自己的单词；其他玩家的棋盘只显示颜色格子，看不到字母。本轮结束后才公开所有人的猜测和答案。

# 计分
- 每轮所有人都猜中或用完 6 次机会后结束，公布答案。
- 猜中得分 = 7 − 所用次数（第 1 次猜中 6 分，第 6 次猜中 1 分）；没猜中 0 分。
- 多人游戏中，本轮第一个猜中的玩家额外 +1 分。
- 也可以选择“放弃本轮”，本轮得 0 分。
- 共进行 1 / 3 / 5 轮（选项），按总分排名，同分名次并列。

# 电脑玩家
- 电脑只根据自己猜过的单词和得到的颜色推理，看不到答案。简单难度经常乱猜；普通难度从符合所有已知颜色的候选词中随机挑一个；困难难度会选择最能缩小候选范围的单词。
''';

const String handleRules = '''
# 汉兜（成语 Wordle）
所有玩家同时猜同一个隐藏的四字成语，每人最多 6 次机会。每次猜测后，系统会从“汉字、声母、韵母、声调”四个层面给出颜色提示，帮你一步步逼近答案。支持 1~8 人。

# 怎么猜
- 输入任意四字成语（必须在内置约 1.8 万条成语词库中），点“提交”。不是成语或字数不对的输入不算次数。
- 答案只会从约 4400 条常用成语中选出。
- 每个格子上方显示该字的拼音，汉字、声母、韵母、声调分别着色。

# 颜色含义
- 汉字：绿色 = 这个字在答案中且位置相同；橙色 = 这个字在答案中但在别的位置；无色 = 答案中没有这个字。
- 声母 / 韵母 / 声调：每一层单独比较。绿色 = 答案同一位置的字声母（韵母、声调）相同；橙色 = 答案其他位置的字有这个声母（韵母、声调）；灰色 = 答案中没有。
- 同一层里重复的项目按原版 Wordle 方式计数：先算绿色，剩下的每个答案项目最多对应一个橙色。
- 零声母字（如“二”“安”）没有声母，不参与声母比较。ü 写作 v，声调 1~4 为四声，轻声单独算一种；“一”“不”等字按成语中的实际变调读音计算。
- 例：答案“一心一意”（词库按实际读音标注变调：yì xīn yí yì），猜“三心二意”（sān xīn èr yì）：心、意 两格全部为绿；“三”的字、声母 s、韵母 an、一声都不在答案中，全灰；“二”是零声母，韵母 er 为灰，但它的四声在答案第 1 个字“一”(yì) 出现，所以声调显示橙色。

# 防抄袭
- 你只能看到自己的成语；其他人的棋盘只显示颜色，看不到汉字和拼音。本轮结束后公开答案和所有人的猜测。

# 计分
- 每轮所有人都猜中或用完机会后结束并公布答案。
- 猜中得分 = 7 − 所用次数；多人游戏中本轮最先猜中者额外 +1 分；没猜中或放弃得 0 分。
- 共进行 1 / 3 / 5 轮（选项），按总分排名。

# 电脑玩家
- 电脑只根据自己猜过的成语和颜色推理，看不到答案。简单难度常常乱猜，普通难度从符合所有颜色提示的候选成语中挑选，困难难度会挑选最能缩小范围的成语。
''';

