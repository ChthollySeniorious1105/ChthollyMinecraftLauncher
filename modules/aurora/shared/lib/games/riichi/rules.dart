const String _basics = '''
# 基本流程
- 136 张牌（万筒索各 1~9、东南西北白发中各 4 张），每人 13 张，庄家先摸。轮流摸一张打一张，凑成 4 组面子（顺子/刻子/杠）+ 1 对雀头即可和牌；另有七对子、国士无双两种特殊型。
- 可吃（仅上家）、碰、明杠、暗杠、加杠；杠后从岭上补牌并翻开新宝牌指示牌。
- 和牌必须至少有 1 番役（宝牌不算役）。自摸和/荣和（点和）；同巡、立直后见逃及舍牌中有听牌则振听，不能荣和。
- 立直：门清听牌、1000 点以上可立直（付 1000 点供托），之后只能摸切；一发、里宝牌、双立直。立直后暗杠不能改变听牌。
- 食替禁止：吃碰后不能立刻打出与鸣牌相同（或同一顺子另一侧）的牌。
- 九种九牌：第一巡、无人鸣牌时，手中有 9 种以上幺九牌可宣告流局（所有模式都可用）。
# 计分
- 符×2^(番+2) 为基本点，5 番满贯、6~7 跳满、8~10 倍满、11~12 三倍满、13 番以上累计役满；役满/双倍役满另计。
- 子家荣和=基本点×4，庄家×6；自摸由三家分担。本场每本 +300 点（自摸各 +100）。
''';

