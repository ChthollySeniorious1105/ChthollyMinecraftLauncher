- 途中流局：九种九牌、四风连打、四家立直、四杠散了（两人以上合计 4 杠）。“三家和了流局”开启时三家同时荣和改为流局，关闭则三人都和。
- 包牌：鸣牌使他人完成大三元/大四喜的第 3 组三元/第 4 组风牌时，放出者负责；自摸时独付该役满，荣和时与放铳者各半。
# 连庄与终局
- 庄家和牌或听牌流局则连庄（本场+1），否则下庄。东风战打完东 4 局、半庄战打完南 4 局结束；有人点数小于 0（飞人）立即结束；终局时庄家为第一且达到 30000 点可和了止め。
- 剩余供托归第一名。名次按最终点数，同分按起家座次（先起家者名次高）。
''';

